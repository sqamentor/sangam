"""Apply UI-PARITY-2 to the CURRENT integration tree as targeted edits.

Every change is a hunk (old block with 3 lines of context -> new block) computed from base-int (the integration
version the worktree was re-synced from) to the worktree version, and replaced in the CURRENT integration file only
when the old block occurs exactly once (the Edit-tool rule). Nothing is copied over a file. EOL style of the
integration file is kept. New files are created only when absent. The OpenAPI yaml is NOT handled here: it is
regenerated by gen_openapi.py afterwards. The register rows/notes are hunks like any other file.

usage: apply_int.py [--dry-run]
"""
import difflib
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from filelist import CHANGED, ADDED  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
INT = r"D:\GITHUB  Project\Custom WorkFlow\.claude\worktrees\workspace-scan-resume-06b524\sangam"
WT = r"C:\Users\LOKEND~2\AppData\Local\Temp\claude\5cef910d4d286f64\898f1ff7-0dcc-4d95-b425-830a9a5ead44\scratchpad\wt-uip2\sangam"
BASE = os.path.join(HERE, 'base-int')
CTX = 3
DRY = '--dry-run' in sys.argv
SKIP = {'sangam-rest/api/sangam-api.yaml'}


def rd(p):
    with open(p, encoding='utf-8', newline='') as fh:
        return fh.read()


def hunks(base_lines, mine_lines):
    """Unified-diff style groups (changes closer than 2*CTX lines share one hunk): (i1, i2, j1, j2) ranges."""
    sm = difflib.SequenceMatcher(a=base_lines, b=mine_lines, autojunk=False)
    return [(g[0][1], g[-1][2], g[0][3], g[-1][4]) for g in sm.get_grouped_opcodes(CTX)]


def apply_file(rel):
    base_raw = rd(os.path.join(BASE, rel))
    cur_raw = rd(os.path.join(INT, rel))
    mine_raw = rd(os.path.join(WT, rel))
    crlf = '\r\n' in cur_raw
    base = base_raw.replace('\r\n', '\n').split('\n')
    mine = mine_raw.replace('\r\n', '\n').split('\n')
    cur = cur_raw.replace('\r\n', '\n')
    drift = base_raw != cur_raw
    hs = hunks(base, mine)
    for i1, i2, j1, j2 in hs:
        # widen the shared context until the old block is unique in the current file (max 12 extra lines)
        for extra in range(0, 13):
            a1, a2 = max(0, i1 - extra), min(len(base), i2 + extra)
            old = base[a1:i1] + base[i1:i2] + base[i2:a2]
            new = base[a1:i1] + mine[j1:j2] + base[i2:a2]
            # whole lines only: sentinel newlines around the file and the block
            old_s, new_s = '\n' + '\n'.join(old) + '\n', '\n' + '\n'.join(new) + '\n'
            n = ('\n' + cur + '\n').count(old_s)
            if n == 1 or n == 0:
                break
        if n != 1:
            return f'REFUSED ({n} matches of a hunk; integration file changed?)'
        cur = ('\n' + cur + '\n').replace(old_s, new_s)[1:-1]
    if not drift and cur != mine_raw.replace('\r\n', '\n'):
        return 'REFUSED (result differs from the worktree version)'
    out = cur.replace('\n', '\r\n') if crlf else cur
    if not DRY:
        with open(os.path.join(INT, rel), 'w', encoding='utf-8', newline='') as fh:
            fh.write(out)
    return f'{len(hs)} hunk(s)' + (' onto a CHANGED integration file' if drift else '')


def main():
    manifest = json.load(open(os.path.join(BASE, 'manifest.json')))
    refused = []
    for rel in CHANGED:
        if rel in SKIP:
            continue
        cur_hash = hashlib.sha256(open(os.path.join(INT, rel), 'rb').read()).hexdigest()
        r = apply_file(rel)
        if r.startswith('REFUSED'):
            refused.append(rel)
        print(f'{"same " if cur_hash == manifest[rel] else "DRIFT"} {r:45} {rel}')
    for rel in ADDED:
        p = os.path.join(INT, rel)
        if os.path.exists(p):
            print('REFUSED (exists in the integration tree)', rel)
            refused.append(rel)
            continue
        if not DRY:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, 'w', encoding='utf-8', newline='') as fh:
                fh.write(rd(os.path.join(WT, rel)))
        print('new  ', rel)
    if refused:
        sys.exit('refused: ' + ', '.join(refused))


if __name__ == '__main__':
    main()
