"""Apply the UI-PARITY-2 changes as targeted edits.

For every file of filelist.CHANGED (except the generated OpenAPI yaml) the change is the set of hunks from BASE (the
integration version the changes were made on) to MINE (my version). Each hunk is replaced in the TARGET file only
when its old block (whole lines, 3 lines of context, widened up to 12 when needed) occurs exactly once: the Edit-tool
rule, so a target that moved on still takes non-overlapping hunks and refuses overlapping ones. The target's EOL style
is kept. filelist.ADDED files are created only when absent in the target. Nothing is copied over an existing file.

usage: apply_hunks.py --base <dir> --mine <sangam dir> --target <sangam dir> [--dry-run]
"""
import argparse
import difflib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from filelist import CHANGED, ADDED  # noqa: E402

SKIP = {'sangam-rest/api/sangam-api.yaml'}   # regenerated by gen_openapi.py, never edited
CTX = 3


def rd(p):
    with open(p, encoding='utf-8', newline='') as fh:
        return fh.read()


def groups(base_lines, mine_lines):
    sm = difflib.SequenceMatcher(a=base_lines, b=mine_lines, autojunk=False)
    return [(g[0][1], g[-1][2], g[0][3], g[-1][4]) for g in sm.get_grouped_opcodes(CTX)]


def apply_file(base_raw, mine_raw, cur_raw):
    base = base_raw.replace('\r\n', '\n').split('\n')
    mine = mine_raw.replace('\r\n', '\n').split('\n')
    cur = cur_raw.replace('\r\n', '\n')
    hs = groups(base, mine)
    for i1, i2, j1, j2 in hs:
        n = 0
        for extra in range(0, 13):
            a1, a2 = max(0, i1 - extra), min(len(base), i2 + extra)
            old_s = '\n' + '\n'.join(base[a1:i2] + base[i2:a2]) + '\n'
            new_s = '\n' + '\n'.join(base[a1:i1] + mine[j1:j2] + base[i2:a2]) + '\n'
            n = ('\n' + cur + '\n').count(old_s)
            if n <= 1:
                break
        if n != 1:
            return None, f'REFUSED ({n} matches of hunk at base line {i1 + 1})'
        cur = ('\n' + cur + '\n').replace(old_s, new_s)[1:-1]
    out = cur.replace('\n', '\r\n') if '\r\n' in cur_raw else cur
    return out, f'{len(hs)} hunk(s)'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--base', required=True)
    ap.add_argument('--mine', required=True)
    ap.add_argument('--target', required=True)
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    refused = []
    for rel in CHANGED:
        if rel in SKIP:
            continue
        base_raw = rd(os.path.join(a.base, rel))
        cur_raw = rd(os.path.join(a.target, rel))
        mine_raw = rd(os.path.join(a.mine, rel))
        out, msg = apply_file(base_raw, mine_raw, cur_raw)
        drift = 'same ' if base_raw == cur_raw else 'DRIFT'
        if out is None:
            refused.append(rel)
        elif base_raw == cur_raw and out.replace('\r\n', '\n') != mine_raw.replace('\r\n', '\n'):
            refused.append(rel)
            msg = 'REFUSED (result differs from my version)'
        elif not a.dry_run and out != cur_raw:
            with open(os.path.join(a.target, rel), 'w', encoding='utf-8', newline='') as fh:
                fh.write(out)
        print(f'{drift} {msg:45} {rel}')
    for rel in ADDED:
        p = os.path.join(a.target, rel)
        if os.path.exists(p):
            same = rd(p).replace('\r\n', '\n') == rd(os.path.join(a.mine, rel)).replace('\r\n', '\n')
            print(('exists (identical)' if same else 'REFUSED (exists, differs)'), rel)
            if not same:
                refused.append(rel)
            continue
        if not a.dry_run:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, 'w', encoding='utf-8', newline='') as fh:
                fh.write(rd(os.path.join(a.mine, rel)))
        print('new  ', rel)
    if refused:
        sys.exit('refused: ' + ', '.join(refused))


if __name__ == '__main__':
    main()
