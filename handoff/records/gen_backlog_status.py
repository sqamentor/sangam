# Generates BACKLOG-STATUS-0.1.0.md from BACKLOG-0.1.0-MASTER.md plus backlog-status.json.
# Fails if an M-id in the json is not in the master, so nothing can drift silently.
import json, os, re, sys, collections
HERE = os.path.dirname(os.path.abspath(__file__))
master = open(os.path.join(HERE, "BACKLOG-0.1.0-MASTER.md"), encoding="utf-8").read().splitlines()
status = json.load(open(os.path.join(HERE, "backlog-status.json"), encoding="utf-8"))
items, epic = [], ""
for line in master:
    m = re.match(r"^### (E\d+)", line)
    if m:
        epic = m.group(1)
    if re.match(r"^\| M-\d{3}", line):
        c = [x.strip() for x in line.split("|")]
        mid = c[1].replace("⚠", "").strip()
        items.append((mid, epic, c[3], c[-3] if len(c) > 3 else "", c[-2]))
ids = {i[0] for i in items}
unknown = [k for k in status if k.startswith("M-") and k not in ids]
if unknown:
    sys.exit("status json names M-ids not in master: " + ", ".join(unknown))
if len(items) != len(ids):
    sys.exit("duplicate M-ids in master")
count = collections.Counter(status.get(i[0], {}).get("status", "NOT_STARTED") for i in items)
out = ["# Backlog status 0.1.0 (generated by gen_backlog_status.py; do not edit by hand)", "",
       "Total M-ids: %d. " % len(items) + ", ".join("%s %d" % (k, v) for k, v in sorted(count.items())), "",
       "| M-id | Epic | Wave | Size | Status | Register | Lane | Note | Scope |", "|---|---|---|---|---|---|---|---|---|"]
for mid, ep, scope, size, wave in items:
    s = status.get(mid, {})
    sc = re.sub(r"\s+", " ", scope)[:110]
    out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (mid, ep, wave, size, s.get("status", "NOT_STARTED"),
               s.get("reg", ""), s.get("lane", ""), s.get("note", "").replace("|", "/"), sc.replace("|", "/")))
open(os.path.join(HERE, "BACKLOG-STATUS-0.1.0.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("items=%d" % len(items), dict(count))
