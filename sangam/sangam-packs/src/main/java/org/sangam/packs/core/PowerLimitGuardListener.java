package org.sangam.packs.core;

import java.math.BigDecimal;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import org.operaton.bpm.engine.ProcessEngineException;
import org.operaton.bpm.engine.ProcessEngineServices;
import org.operaton.bpm.engine.delegate.DelegateTask;
import org.operaton.bpm.engine.delegate.Expression;
import org.operaton.bpm.engine.delegate.TaskListener;
import org.operaton.bpm.engine.repository.ProcessDefinition;

import org.sangam.core.power.LegacyPowerContracts;
import org.sangam.core.power.ManifestOperationMetadata;
import org.sangam.core.power.PowerLimitEvaluator;
import org.sangam.core.power.PowerOutcome;
import org.sangam.core.power.PowerRequest;
import org.sangam.core.power.PowerRuleSource;
import org.sangam.packs.port.PackRuntime;

/**
 * Delegated-power check at the moment of sanction (K6, IX.5 rule 3, J-P3-E05), through the one power-limit evaluator
 * of {@code sangam-core} (owner decisions 142 and 193).
 *
 * <ul>
 *   <li>The case type is the process definition that called the core sanction (key and engine version) and the action
 *       is the id of that call activity. Whether the action is monetary, its currency and its limit table come only
 *       from the deployed manifest of that pack version ({@link PackPowers}, generated by packgen); a process
 *       variable such as {@code powersDecisionKey} is never read for them. No declaration: denied.</li>
 *   <li>The limit table is the one current on the action date (the tenant's own table first, decision 202), with
 *       inputs {@code seatRole}, {@code amount} and {@code caseType}; the case type is the manifest's
 *       {@code ruleCaseType} for the action (decision 222, derived by packgen from the calling process) or absent, and
 *       a case variable of that name is never used. Its single row ({@code powerLimit}, optional
 *       {@code allowed} and {@code noMonetaryLimit}) maps through {@link LegacyPowerContracts#listenerRow}.</li>
 *   <li>The amount is the case's exact decimal {@code amount} (minor units of the pack currency); a monetary action
 *       without one is denied. A non-monetary action is decided by the table row alone.</li>
 * </ul>
 * Every evaluation writes {@code POWER_LIMIT_DECISION} with the evaluator's payload and {@code RULE_EVALUATED} for the
 * table; a refusal also writes {@code POWER_LIMIT_EXCEEDED} and fails the completion with {@code 422
 * POWER_LIMIT_EXCEEDED}, and the officer forwards instead.
 *
 * <p>Fields: {@code decisionVar}, {@code approveValues} (comma list, default {@code approve}), {@code amountVar}
 * (default {@code amount}).
 */
public class PowerLimitGuardListener implements TaskListener {

    private Expression decisionVar;
    private Expression approveValues;
    private Expression amountVar;

    @Override
    public void notify(DelegateTask t) {
        String dv = Vars.field(decisionVar, t, "decision");
        Object decision = t.getVariable(dv);
        if (decision == null || !Vars.csv(Vars.field(approveValues, t, "approve")).contains(decision.toString())) {
            return;
        }
        String tenant = Vars.tenant(t);
        TaskActor a = TaskActor.of(t);
        String role = a.seat() == null ? null : PackRuntime.seats().roleOf(tenant, a.seat()).orElse(a.seat());
        BigDecimal amount = Vars.decimal(t, Vars.field(amountVar, t, "amount"));
        ProcessEngineServices services = t.getProcessEngineServices();
        PackPowers powers = new PackPowers(services.getRepositoryService());

        PackPowers.Caller caller = PackPowers.caller(t.getExecution());
        String caseType = null;
        int caseTypeVersion = 0;
        String currency = null;
        if (caller != null) {
            ProcessDefinition def = powers.definition(caller);
            caseType = def.getKey();
            caseTypeVersion = def.getVersion();
            currency = powers.manifest(tenant, caseType, caseTypeVersion).map(PackPowers.Manifest::currency)
                    .orElse(null);
        }
        String tableCurrency = currency;
        Decisions.Evaluation[] evaluated = new Decisions.Evaluation[1];
        Map<String, Object> row = new HashMap<>();
        PowerRuleSource rules = (request, cls) -> {
            Map<String, Object> in = new HashMap<>(t.getVariables()); // tables may key on any case field (subject head)
            in.put("seatRole", role);
            in.put("amount", amount == null ? BigDecimal.ZERO : amount); // exact: band boundaries (SG-01)
            // decision 222: the table's caseType is the manifest's ruleCaseType or none, never a case variable
            Decisions.Evaluation ev = Decisions.evaluate(services, tenant, cls.limitTableKey(), cls.ruleInputs(in));
            evaluated[0] = ev;
            row.putAll(ev.single());
            return new PowerRuleSource.ApplicableRules(List.of(LegacyPowerContracts.listenerRow(cls.limitTableKey(),
                    String.valueOf(ev.version()), row, cls.monetary() ? cls.currency() : tableCurrency)), List.of());
        };
        PowerRequest request = new PowerRequest(a.person(), caller == null ? null : caller.activityId(), tenant, null,
                caseType, caseTypeVersion, amount, currency, Vars.intVal(t, Vars.CASE_VERSION, 0));
        PowerOutcome outcome = new PowerLimitEvaluator(new ManifestOperationMetadata(powers), rules).evaluate(request);

        Vars.auditTask(t, PowerOutcome.AUDIT_EVENT, a.person(), a.seat(), null, a.authorityBasis(),
                new HashMap<>(outcome.auditPayload()));
        BigDecimal limit = Vars.decimal(row.get("powerLimit"));
        boolean unlimited = Boolean.TRUE.equals(row.get("noMonetaryLimit"));
        if (evaluated[0] != null) {
            Decisions.Evaluation ev = evaluated[0];
            Vars.auditTask(t, "RULE_EVALUATED", a.person(), a.seat(), null, a.authorityBasis(),
                    Vars.map("decision", ev.key(), "version", ev.version(), "seatRole", role, "powerLimit",
                            unlimited ? "NO_MONETARY_LIMIT" : limit == null ? null : limit.toPlainString(), "amount",
                            amount == null ? null : amount.toPlainString(), "result", outcome.permitted()));
            t.getExecution().setVariable("approvalRuleVersion", ev.key() + ":" + ev.version());
        }
        if (!outcome.permitted()) {
            Vars.auditTask(t, "POWER_LIMIT_EXCEEDED", a.person(), a.seat(), null, a.authorityBasis(),
                    Vars.map("powerLimit", limit == null ? null : limit.toPlainString(),
                            "amount", amount == null ? null : amount.toPlainString(), "reason", outcome.reason()));
            throw new ProcessEngineException("422 POWER_LIMIT_EXCEEDED: " + outcome.reason()
                    + ". Forward to the competent authority.");
        }
    }
}
