def of(connector_id):
    """The declared money movement of a connector; KeyError for a connector nobody classified."""
    if connector_id not in MOVEMENT:
        raise KeyError(f'connector {connector_id} has no money movement (owner decision A1): add it to '
                       f'money_movement.MOVEMENT')
    return MOVEMENT[connector_id]