package org.sangam.resources.dialect;

import org.sangam.core.layer.Dialect;
import org.sangam.core.layer.Jdbc;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.util.Locale;
import java.util.Map;

/**
 * The SQL variants the resources module needs (A-15: every statement is per dialect). It covers the four Tier-1
 * databases plus H2 (development only). The core {@link Dialect} has no H2 entry and core files are not changed, so
 * this enum carries H2 (run with {@code MODE=PostgreSQL}) and maps to the core enum where core helpers are reused.
 *
 * <h2>No double booking: the exclusion strategy per dialect</h2>
 * PostgreSQL exclusion constraints ({@code EXCLUDE USING gist}) are not used because Oracle, SQL Server and MySQL lack
 * them. Every dialect uses the same two mechanisms, specialised only at the statement level:
 * <ol>
 *   <li><b>Slot-granular claim rows</b> ({@code RES_CLAIM}, primary key (tenant, resource, slot_key, unit_no)). A booking
 *       inserts one row per (slot, capacity unit). Two concurrent bookings of the same unit and slot collide on the
 *       primary key, so the database itself rejects the second one, under any isolation level:
 *       <ul>
 *         <li>PostgreSQL: {@code INSERT .. ON CONFLICT DO NOTHING} (a plain duplicate would abort the transaction);
 *             the second inserter waits for the first to commit and then sees 0 rows inserted;</li>
 *         <li>Oracle: plain insert, ORA-00001 (statement-level rollback, the transaction stays usable);</li>
 *         <li>SQL Server: plain insert, error 2627/2601 (statement-terminating while {@code XACT_ABORT} is OFF, the
 *             server default; RCSI required);</li>
 *         <li>MySQL 8.4 (InnoDB, READ COMMITTED): plain insert, error 1062 (only the statement rolls back);</li>
 *         <li>H2: plain insert, SQLState 23505.</li>
 *       </ul></li>
 *   <li><b>Resource-row serialisation for long allotments</b>: an allotment locks its {@code RES_RESOURCE} row
 *       ({@link #lockingSelect}) and checks for an overlapping active allotment while the lock is held; the lock is the
 *       resource-scoped exclusive lease of R35 within the database transaction. PostgreSQL/MySQL/H2 {@code FOR UPDATE},
 *       Oracle {@code FOR UPDATE WAIT n}, SQL Server {@code WITH (UPDLOCK, HOLDLOCK, ROWLOCK)}.</li>
 * </ol>
 */
public enum ResourcesDialect {
    POSTGRESQL, ORACLE, SQLSERVER, MYSQL, H2;

    private static final Map<String, String> H2_TYPES = Map.of(
            "{str}", "VARCHAR(255)", "{str64}", "VARCHAR(64)", "{long}", "BIGINT", "{int}", "INTEGER",
            "{small}", "SMALLINT", "{bytes32}", "VARBINARY(32)", "{blob}", "BLOB", "{text}", "CLOB",
            "{ts}", "TIMESTAMP WITH TIME ZONE", "{identity}", "BIGINT GENERATED BY DEFAULT AS IDENTITY");

    public static ResourcesDialect of(Dialect d) {
        return switch (d) {
            case POSTGRESQL -> POSTGRESQL;
            case ORACLE -> ORACLE;
            case SQLSERVER -> SQLSERVER;
            case MYSQL -> MYSQL;
        };
    }

    /** Detects the dialect from JDBC metadata; MariaDB is treated as MySQL (LIC-4). */
    public static ResourcesDialect detect(Connection c) {
        try {
            String p = c.getMetaData().getDatabaseProductName().toLowerCase(Locale.ROOT);
            if (p.contains("postgres")) {
                return POSTGRESQL;
            }
            if (p.contains("oracle")) {
                return ORACLE;
            }
            if (p.contains("microsoft") || p.contains("sql server")) {
                return SQLSERVER;
            }
            if (p.contains("mysql") || p.contains("mariadb")) {
                return MYSQL;
            }
            if (p.contains("h2")) {
                return H2;
            }
            throw new IllegalStateException("unsupported database: " + p);
        } catch (SQLException e) {
            throw new IllegalStateException("cannot read database metadata", e);
        }
    }

    /** Core dialect for reused core helpers (H2 runs in PostgreSQL mode). */
    public Dialect core() {
        return switch (this) {
            case POSTGRESQL, H2 -> Dialect.POSTGRESQL;
            case ORACLE -> Dialect.ORACLE;
            case SQLSERVER -> Dialect.SQLSERVER;
            case MYSQL -> Dialect.MYSQL;
        };
    }

    /** Expands the portable DDL type tokens. */
    public String expand(String template) {
        if (this != H2) {
            return core().expand(template);
        }
        String out = template;
        for (Map.Entry<String, String> e : H2_TYPES.entrySet()) {
            out = out.replace(e.getKey(), e.getValue());
        }
        return out;
    }

    public String createTableSuffix() {
        return this == MYSQL ? Dialect.MYSQL.createTableSuffix() : "";
    }

    /** Database clock (A-1). */
    public String now() {
        return switch (this) {
            case POSTGRESQL, H2 -> "CURRENT_TIMESTAMP";
            case ORACLE -> "SYSTIMESTAMP";
            case SQLSERVER -> "SYSDATETIMEOFFSET()";
            case MYSQL -> "UTC_TIMESTAMP(6)";
        };
    }

    public String fromDual() {
        return this == ORACLE ? " FROM DUAL" : "";
    }

    /** Appends paging to an ordered select (values validated and inlined). */
    public String page(String orderedSelect, int offset, int limit) {
        if (offset < 0 || limit <= 0) {
            throw new IllegalArgumentException("offset must be >= 0 and limit > 0");
        }
        return switch (this) {
            case POSTGRESQL, MYSQL, H2 -> orderedSelect + " LIMIT " + limit + " OFFSET " + offset;
            case ORACLE, SQLSERVER -> orderedSelect + " OFFSET " + offset + " ROWS FETCH NEXT " + limit + " ROWS ONLY";
        };
    }

    /** A blocking row lock by key (resource serialisation, counters). */
    public String lockingSelect(String columns, String table, String where) {
        return switch (this) {
            case POSTGRESQL, MYSQL, H2 -> "SELECT " + columns + " FROM " + table + " WHERE " + where + " FOR UPDATE";
            case ORACLE -> "SELECT " + columns + " FROM " + table + " WHERE " + where + " FOR UPDATE WAIT 5";
            case SQLSERVER -> "SELECT " + columns + " FROM " + table + " WITH (UPDLOCK, HOLDLOCK, ROWLOCK) WHERE " + where;
        };
    }

    /**
     * A row-locking select that skips rows locked by other transactions (queue call-next, hold sweeper).
     * Oracle uses core's ordered candidate-window form (core {@code Dialect.skipLockedSelect}), so order and
     * concurrent claimers are handled the same way as in the core relay and inbox.
     */
    public String skipLockedSelect(String columns, String table, String alias, String where, String orderBy, int limit) {
        if (limit <= 0) {
            throw new IllegalArgumentException("limit must be positive");
        }
        return switch (this) {
            case POSTGRESQL -> "SELECT " + columns + " FROM " + table + " " + alias + " WHERE " + where
                    + " ORDER BY " + orderBy + " LIMIT " + limit + " FOR UPDATE OF " + alias + " SKIP LOCKED";
            case ORACLE -> org.sangam.core.layer.Dialect.ORACLE.skipLockedSelect(columns, table, alias, where, orderBy, limit);
            case SQLSERVER -> "SELECT TOP (" + limit + ") " + columns + " FROM " + table + " " + alias
                    + " WITH (UPDLOCK, READPAST, ROWLOCK) WHERE " + where + " ORDER BY " + orderBy;
            case MYSQL -> "SELECT " + columns + " FROM " + table + " " + alias + " WHERE " + where
                    + " ORDER BY " + orderBy + " LIMIT " + limit + " FOR UPDATE SKIP LOCKED";
            // H2 2.x has no SKIP LOCKED; a plain FOR UPDATE (development only) serialises callers instead
            case H2 -> "SELECT " + columns + " FROM " + table + " " + alias + " WHERE " + where
                    + " ORDER BY " + orderBy + " LIMIT " + limit + " FOR UPDATE";
        };
    }

    /** Duplicate-key classification (X.2.2.8). */
    public boolean isUniqueViolation(SQLException e) {
        for (Throwable t = e; t != null; t = t.getCause()) {
            if (t instanceof SQLException s) {
                boolean dup = switch (this) {
                    case POSTGRESQL, H2 -> "23505".equals(s.getSQLState());
                    case ORACLE -> s.getErrorCode() == 1;
                    case SQLSERVER -> s.getErrorCode() == 2627 || s.getErrorCode() == 2601;
                    case MYSQL -> s.getErrorCode() == 1062 || s.getErrorCode() == 1586;
                };
                if (dup) {
                    return true;
                }
            }
        }
        return false;
    }

    /** Retryable lock/serialisation failures. */
    public boolean isRetryable(SQLException e) {
        if (this == H2) {
            return "40001".equals(e.getSQLState()) || "HYT00".equals(e.getSQLState());
        }
        return core().isRetryable(e);
    }

    /**
     * The exclusion primitive: inserts a claim row and reports whether this transaction now owns the key. Never leaves
     * the transaction aborted (PostgreSQL {@code ON CONFLICT DO NOTHING}; elsewhere a statement-level duplicate).
     */
    public boolean insertIfAbsent(Connection c, String insertSql, Object... params) {
        if (this == POSTGRESQL) {
            return Jdbc.update(c, insertSql + " ON CONFLICT DO NOTHING", params) == 1;
        }
        try (PreparedStatement ps = c.prepareStatement(insertSql)) {
            Jdbc.bind(ps, 1, params);
            return ps.executeUpdate() == 1;
        } catch (SQLException e) {
            if (isUniqueViolation(e)) {
                return false;
            }
            throw new Jdbc.LayerSqlException(insertSql, e);
        }
    }
}
