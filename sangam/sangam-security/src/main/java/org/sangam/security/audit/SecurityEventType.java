package org.sangam.security.audit;

/**
 * Security, authority and admin audit event names (normative per SANGAM.md X.5.2; catalogue X.4.0.3 and the class-B
 * minimum set X.2.3.2). Events with no root go to the tenant security chain {@code sec:<tenant>} (X.2.3.3 rule 2);
 * case events go to the root chain.
 */
public enum SecurityEventType {
    // identity
    AUTH_LOGIN, AUTH_LOGOUT, LOGIN_BATCH, LOGIN_FAILED, SESSION_EXPIRED, SEAT_CONTEXT_SELECTED, AUTH_DENIED,
    API_TOKEN_ISSUED, API_TOKEN_REVOKED, USER_PROVISIONED, USER_UPDATED, USER_DISABLED, IDP_CONFIGURED, DIRECTORY_SYNCED,
    // tasks / authority (root chain)
    TASK_ASSIGNED, TASK_REASSIGNED, TASK_ACTED_FOR, ACTED_FOR, APPROVAL_RECORDED, APPROVAL_INVALIDATED,
    SOD_VIOLATION_BLOCKED, SOD_EXCEPTION_REQUESTED, SOD_EXCEPTION_GRANTED, SOD_EXCEPTION_REJECTED,
    POWER_LIMIT_EXCEEDED, AUTHORITY_DECISION, ROUTING_DECISION,
    // grants (security chain)
    GRANT_CHANGED, DENY_CHANGED, MEMBERSHIP_CHANGED, SEAT_HOLDER_CHANGED, PRIVILEGE_CHANGED, POLICY_CHANGE_PENDING,
    SENSITIVE_READ, EXPORT, READ_AUDIT, AUDIT_VIEWED, AUDIT_EXPORTED,
    // admin
    TENANT_CREATED, TENANT_CONFIGURED, TENANT_ACTIVATED, TENANT_SUSPENDED, SEAT_CREATED, SEAT_MOVED, SEAT_ABOLISHED,
    ORG_UNIT_CREATED, ORG_UNIT_MOVED, ORG_UNIT_RENAMED, POSTING_EFFECTIVE, POSTING_ENDED, ADDITIONAL_CHARGE_GRANTED, LEAVE_RECORDED,
    DELEGATION_GRANTED, DELEGATION_EXPIRED, PACKAGE_SUBMITTED_FOR_REVIEW, PACKAGE_APPROVED, PACKAGE_PUBLISHED,
    PACKAGE_RETIRED, WORKER_BOUND, WORKER_UNBOUND, BULK_OPERATION_APPROVED, OPERATOR_ACTION,
    // quotas (SL-43; chain quota:<tenant>, written by JdbcTenantQuotas)
    TENANT_QUOTA_EXCEEDED
}
