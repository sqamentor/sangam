package org.sangam.core.layer;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.Map;
import java.util.UUID;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

/**
 * SL-16: the ledger calls the worker API uses for an external worker: A-14 binding of the engine work, an
 * outcome-unknown report that carries the task and the worker's details, and the reopen of a reported technical
 * failure (fenced; only FAILED rows move).
 */
class OperationLedgerWorkerPathH2Test {

    Connection c;
    OperationLedger ledger;
    final OperationLedger.OperationRef ref = new OperationLedger.OperationRef("t1", "root-1", "act-1", 0);
    final UUID op = UUID.randomUUID();

    @BeforeEach
    void setUp() throws Exception {
        c = DriverManager.getConnection("jdbc:h2:mem:wl" + UUID.randomUUID() + ";MODE=PostgreSQL", "sa", "");
        try (Statement s = c.createStatement()) {
            s.execute("CREATE TABLE OPERATION_LEDGER (operation_id VARCHAR(64) NOT NULL PRIMARY KEY, tenant_id VARCHAR(64) NOT NULL,"
                    + " root_id VARCHAR(64) NOT NULL, activity_instance_id VARCHAR(255) NOT NULL, loop_counter INTEGER NOT NULL,"
                    + " capability_class VARCHAR(64) NOT NULL, request_fingerprint VARBINARY(32), state VARCHAR(64) NOT NULL,"
                    + " attempt_id VARCHAR(64), lock_version BIGINT NOT NULL, attempts INTEGER NOT NULL, outcome CHARACTER LARGE OBJECT,"
                    + " created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,"
                    + " engine_work_id VARCHAR(64), business_key VARCHAR(255), topic VARCHAR(255))");
            s.execute("CREATE TABLE RECONCILIATION_ITEM (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id VARCHAR(64) NOT NULL,"
                    + " kind VARCHAR(64) NOT NULL, operation_id VARCHAR(64), root_id VARCHAR(64), task_id VARCHAR(64), state VARCHAR(64) NOT NULL,"
                    + " details CHARACTER LARGE OBJECT, action VARCHAR(64), resolved_by VARCHAR(255), resolution CHARACTER LARGE OBJECT,"
                    + " created_at TIMESTAMP WITH TIME ZONE NOT NULL, resolved_at TIMESTAMP WITH TIME ZONE, engine_work_id VARCHAR(64))");
        }
        ledger = new OperationLedger(Dialect.POSTGRESQL, new ReconciliationQueue(Dialect.POSTGRESQL, null));
    }

    @AfterEach
    void tearDown() throws Exception {
        c.close();
    }

    @Test
    void bindsTheEngineWork() {
        ledger.recordIntent(c, op, ref, null, null, "att-1", 1);
        ledger.bindEngineWork(c, op, "work-1");
        assertEquals(op, ledger.findByEngineWork(c, "work-1").orElseThrow().operationId());
        assertTrue(ledger.findByEngineWork(c, "work-2").isEmpty());
    }

    @Test
    void outcomeUnknownCarriesTheTaskAndDetails() {
        ledger.recordIntent(c, op, ref, CapabilityClass.A_IDEMPOTENT_WITH_LOOKUP, null, "att-1", 1);
        long item = ledger.markUnknown(c, op, 1, "work-1", Map.of("detail", "timeout after send"));
        assertEquals(OperationLedger.State.UNKNOWN_OUTCOME, ledger.find(c, op).orElseThrow().state());
        ReconciliationQueue.Item i = new ReconciliationQueue(Dialect.POSTGRESQL, null).get(c, item).orElseThrow();
        assertEquals(op, i.operationId());
        assertEquals("work-1", i.taskId());
        assertEquals("root-1", i.rootId());
        assertTrue(i.details().contains("timeout after send") && i.details().contains("A_IDEMPOTENT_WITH_LOOKUP"), i.details());
        assertThrows(OperationLedger.StaleLeaseException.class,
                () -> ledger.markUnknown(c, op, 0, "work-1", Map.of()), "fenced by lockVersion");
    }

    @Test
    void reopensOnlyAFailedOperationAndIsFenced() {
        ledger.recordIntent(c, op, ref, null, null, "att-1", 3);
        OperationLedger.Intent notFailed = ledger.reopenFailed(c, op, "att-2", 5);
        assertEquals(OperationLedger.State.INTENT, notFailed.state());
        assertEquals(1, ledger.find(c, op).orElseThrow().attempts(), "an INTENT row is not touched");

        ledger.recordOutcome(c, op, 3, false, "{\"code\":\"TECHNICAL_FAILURE\"}");
        assertThrows(OperationLedger.StaleLeaseException.class, () -> ledger.reopenFailed(c, op, "att-0", 2));
        OperationLedger.Intent reopened = ledger.reopenFailed(c, op, "att-2", 5);
        assertEquals(OperationLedger.State.INTENT, reopened.state());
        assertTrue(reopened.mayDispatch());
        assertEquals(2, reopened.attempts());
        OperationLedger.Entry e = ledger.find(c, op).orElseThrow();
        assertEquals(5, e.lockVersion());
        assertEquals("att-2", e.attemptId());
        assertNull(e.outcome());

        ledger.recordOutcome(c, op, 5, true, "{\"providerRef\":\"R\"}");
        assertEquals(OperationLedger.State.SUCCEEDED, ledger.reopenFailed(c, op, "att-3", 7).state(), "SUCCEEDED never reopens");
    }
}
