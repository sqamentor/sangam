package org.sangam.sdk.spring;

import java.time.Duration;

/**
 * {@code sangam.worker.*} settings of the Spring Boot adapter (M-027). The token is read from configuration (an
 * environment variable or a secret store bound by Spring); a {@code TokenProvider} bean replaces it.
 */
public class SangamWorkerProperties {

    /** Run the worker in this application (default true when the adapter is on the classpath). */
    private boolean enabled = true;
    /** Base URL of the Sangam API, e.g. {@code https://sangam.example.org/api/v1}. */
    private String baseUrl;
    /** Static bearer token; ignored when a {@code TokenProvider} bean exists. */
    private String token;
    /** Worker id (default: generated by the SDK). */
    private String workerId;
    /** Handlers running at the same time (default: the SDK default). */
    private Integer maxConcurrency;
    /** Items per fetch (default: the SDK default). */
    private Integer maxTasksPerFetch;
    /** Long-poll wait per fetch (default: the SDK default). */
    private Duration asyncResponseTimeout;
    /** Time the stop waits for running handlers (default: the SDK default). */
    private Duration shutdownTimeout;

    public boolean isEnabled() { return enabled; }
    public void setEnabled(boolean enabled) { this.enabled = enabled; }
    public String getBaseUrl() { return baseUrl; }
    public void setBaseUrl(String baseUrl) { this.baseUrl = baseUrl; }
    public String getToken() { return token; }
    public void setToken(String token) { this.token = token; }
    public String getWorkerId() { return workerId; }
    public void setWorkerId(String workerId) { this.workerId = workerId; }
    public Integer getMaxConcurrency() { return maxConcurrency; }
    public void setMaxConcurrency(Integer maxConcurrency) { this.maxConcurrency = maxConcurrency; }
    public Integer getMaxTasksPerFetch() { return maxTasksPerFetch; }
    public void setMaxTasksPerFetch(Integer maxTasksPerFetch) { this.maxTasksPerFetch = maxTasksPerFetch; }
    public Duration getAsyncResponseTimeout() { return asyncResponseTimeout; }
    public void setAsyncResponseTimeout(Duration asyncResponseTimeout) { this.asyncResponseTimeout = asyncResponseTimeout; }
    public Duration getShutdownTimeout() { return shutdownTimeout; }
    public void setShutdownTimeout(Duration shutdownTimeout) { this.shutdownTimeout = shutdownTimeout; }
}
