"""Python emitter: TypedDicts (wire names exactly) in sangam_sdk/generated/models.py, one API class per tag in
sangam_sdk/generated/api.py and the SangamApis facade. Runtime: the SDK's own HttpTransport (urllib); no new
dependency. Python 3.10 compatible (required keys use a TypedDict base class instead of typing.Required)."""
from __future__ import annotations

import keyword
import re

from api_groups import Group
from contract_ir import Contract, Operation, T, pascal, snake

BASE = "python/src/sangam_sdk/generated"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
SOFT = {"match", "case", "type", "_"}


def ident(name: str) -> str:
    i = snake(name)
    if not i or i[0].isdigit():
        i = "n_" + i
    return i + "_" if keyword.iskeyword(i) or i in SOFT else i


def pystr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def pdoc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def ptype(t: T, ns: str = "") -> str:
    k = t.kind
    if k == "ref":
        return ns + t.name
    if k == "string":
        return "Literal[" + ", ".join(pystr(v) for v in t.enum) + "]" if t.enum else "str"
    if k in ("datetime", "date", "binary"):
        return "str"
    if k in ("int32", "int64"):
        return "int"
    if k in ("double", "decimal"):
        return "Number"
    if k == "boolean":
        return "bool"
    if k == "array":
        return f"list[{ptype(t.item, ns)}]"
    if k == "map":
        return f"dict[str, {ptype(t.item, ns)}]"
    return "Any"


def header(version: str) -> str:
    return ("# SPDX-License-Identifier: Apache-2.0\n"
            f"# GENERATED by sdks/codegen/generate_sdk_surface.py from sangam-rest/api/sangam-api.yaml {version}."
            " Do not edit.\n")


def models(c: Contract) -> str:
    out = [header(c.version),
           '"""Wire models of sangam-api.yaml as TypedDicts: keys are the camelCase wire names, exactly as sent and',
           "received. Decimals arrive as decimal.Decimal (the transport parses JSON numbers with a fraction exactly);",
           'date-time and date values are ISO-8601 strings."""',
           "from __future__ import annotations", "",
           "from decimal import Decimal",
           "from typing import Any, Literal, TypedDict, Union", "",
           "Number = Union[int, float, Decimal]", "",
           "__all__ = [\"Number\", " + ", ".join(pystr(n) for n in c.models) + "]", ""]
    for m in c.models.values():
        doc = pdoc((m.description or f"Contract schema {m.name}.") + f"\n\nSchema ``{m.name}``.")
        if m.extras is not None:
            doc += "\n\nThe schema allows members it does not name (additionalProperties); they are kept as received."
        functional = any(not IDENT.match(p.wire) or keyword.iskeyword(p.wire) for p in m.props)
        req = [p for p in m.props if p.required]
        opt = [p for p in m.props if not p.required]
        if functional:
            # a wire name that is not a Python identifier: the functional form keeps it; required keys are documented
            fields = ", ".join(f"{pystr(p.wire)}: {pystr(ptype(p.type))}" for p in m.props)
            if req:
                doc += "\n\nRequired keys: " + ", ".join(p.wire for p in req) + "."
            out.append(f"{m.name} = TypedDict({pystr(m.name)}, {{{fields}}}, total=False)")
            out.append(f'{m.name}.__doc__ = """{doc}"""')
            out.append("")
            continue
        base = "TypedDict"
        if req and opt:
            out.append(f"class _{m.name}Required(TypedDict):")
            for p in req:
                out.append(f"    {p.wire}: {ptype(p.type)}")
            out.append("")
            out.append("")
            base = f"_{m.name}Required"
        total = "" if not opt else ", total=False"
        out.append(f"class {m.name}({base}{total}):")
        out.append(f'    """{doc}"""')
        for p in (opt if req and opt else m.props):
            out.append(f"    {p.wire}: {ptype(p.type)}")
        out.append("")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def body_type(op: Operation) -> str:
    b = op.body
    if b is None:
        return ""
    if b.kind == "json":
        return ptype(b.type, "M.")
    if b.kind == "multipart":
        return "Mapping[str, Any]"
    return "Union[bytes, str]"


def result_type(op: Operation) -> str:
    r = op.response
    if r.kind == "none":
        return "None"
    if r.kind in ("raw", "sse"):
        return "bytes"
    if r.paged:
        return f"Page[{ptype(r.type.item, 'M.')}]"
    return ptype(r.type, "M.")


def path_expr(op: Operation, names: dict[str, str]) -> str:
    s = op.path.replace("{", "{{").replace("}", "}}")
    s = re.sub(r"{{([^}]+)}}", lambda mt: "{seg(str(" + names[mt.group(1)] + "))}", s)
    return 'f"' + s + '"'


def method(op: Operation) -> str:
    used = {"self", "options", "body", "req"}
    names: dict[str, str] = {}
    args = ["self"]
    for p in op.path_params:
        i = ident(p.wire)
        while i in used:
            i += "_"
        used.add(i)
        names[p.wire] = i
        args.append(f"{i}: {'Union[str, int]' if p.type.kind in ('int32', 'int64') else 'str'}")
    if op.body is not None:
        bt = body_type(op)
        args.append(f"body: {bt}" if op.body.required else f"body: Optional[{bt}] = None")
    kw = []
    pnames: dict[str, str] = {}
    for p in op.required_params + op.optional_params:
        i = ident(p.wire)
        while i in used:
            i += "_"
        used.add(i)
        pnames[p.wire] = i
        kw.append(f"{i}: {ptype(p.type, 'M.')}" if p.required else f"{i}: Optional[{ptype(p.type, 'M.')}] = None")
    kw.append("options: Optional[RequestOptions] = None")
    args.append("*")
    args += kw
    rt = result_type(op)
    flags = []
    if op.permission:
        flags.append(f"permission ``{op.permission}``")
    if op.fenced:
        flags.append("fenced by (workerId, lockVersion, attemptId): 409 STALE_LEASE changes nothing (VI.3)")
    if op.idempotent:
        flags.append("result stored atomically with the state change")
    text = op.summary or op.op_id
    if op.description and op.description != op.summary:
        text += "\n\n" + op.description
    text += f"\n\n``{op.method} {op.path}`` (operationId ``{op.op_id}``)" + ("; " + "; ".join(flags) if flags else "") + "."
    if op.deprecated:
        text += "\n\nDeprecated in the contract."
    doc = "\n".join(("        " + l) if l else "" for l in pdoc(text).splitlines()).lstrip()
    lines = [f"    def {ident(op.op_id)}(" + ", ".join(args) + f") -> {rt}:", f'        """{doc}', '        """']
    q = [f"{pystr(p.wire)}: {pnames[p.wire]}" for p in op.query_params]
    h = [f"{pystr(p.wire)}: {pnames[p.wire]}" for p in op.header_params]
    lines.append(f"        req = ApiRequest({pystr(op.method)}, {path_expr(op, names)}"
                 + (f", query={{{', '.join(q)}}}" if q else "") + ")")
    if h:
        lines.append(f"        _headers(req, {{{', '.join(h)}}})")
    if op.body is not None:
        if op.body.kind == "json":
            lines.append("        req.body = body")
        elif op.body.kind == "multipart":
            lines.append("        _multipart(req, body)")
        else:
            lines.append(f"        _raw(req, body, {pystr(op.body.media)}, options)")
    r = op.response
    if r.kind == "none":
        lines.append("        self._c.none(req, options)")
    elif r.kind in ("raw", "sse"):
        lines.append(f"        return self._c.raw(req, options, {pystr(r.media)})")
    elif r.paged:
        lines.append(f"        return cast({pystr(rt)}, self._c.page(req, options, {pnames['page']}, {pnames['size']}))")
    else:
        lines.append(f"        return cast({pystr(rt)}, self._c.json(req, options))")
    return "\n".join(lines)


SUPPORT = '''
import uuid
from dataclasses import dataclass, field
from typing import Any, Literal, Mapping, Optional, Union, cast

from ..http import ApiRequest, HttpTransport, seg
from ..models import Page
from . import models as M  # noqa: F401  (annotations name the wire models as M.<Schema>)
from .models import Number  # noqa: F401  (decimal parameters)

_ = Literal  # enum parameters are annotated as Literal[...]


@dataclass
class RequestOptions:
    """Per-call options of a generated operation.

    ``idempotency_key`` is sent as ``Idempotency-Key`` (R41); on a mutation without one the transport generates one per
    logical call. ``seat`` / ``acting_for_seat`` set ``X-Sangam-Seat`` / ``X-Sangam-Acting-For-Seat`` for this call.
    ``content_type`` chooses the media type of a raw body when the operation accepts several.
    """

    idempotency_key: Optional[str] = None
    seat: Optional[str] = None
    acting_for_seat: Optional[str] = None
    timeout: Optional[float] = None
    content_type: Optional[str] = None
    headers: dict[str, str] = field(default_factory=dict)


def _headers(req: ApiRequest, values: Mapping[str, Any]) -> None:
    for k, v in values.items():
        if v is not None:
            req.headers[k] = v if isinstance(v, str) else str(v).lower() if isinstance(v, bool) else str(v)


def _raw(req: ApiRequest, body: Union[bytes, str, None], media: str, o: Optional[RequestOptions]) -> None:
    if body is None:
        return
    req.raw_body = body.encode("utf-8") if isinstance(body, str) else body
    req.raw_content_type = o.content_type if o is not None and o.content_type else media


def _multipart(req: ApiRequest, parts: Optional[Mapping[str, Any]]) -> None:
    """multipart/form-data. A ``(filename, bytes)`` or ``(filename, bytes, content_type)`` tuple or a bytes value is a
    file part (bytes are named after the part); a list repeats the part per element (e.g. several deployment files);
    anything else is a text part."""
    if parts is None:
        return
    boundary = "sangam-" + str(uuid.uuid4())
    out = bytearray()

    def q(s: str) -> str:
        return s.replace('"', "%22").replace("\\r", "").replace("\\n", "")

    def part(name: str, value: Any) -> None:
        if value is None:
            return
        out.extend(f"--{boundary}\\r\\n".encode())
        if isinstance(value, tuple) and len(value) in (2, 3) and isinstance(value[1], (bytes, bytearray)):
            ct = value[2] if len(value) == 3 else "application/octet-stream"
            out.extend(f'Content-Disposition: form-data; name="{q(name)}"; filename="{q(str(value[0]))}"\\r\\n'.encode())
            out.extend(f"Content-Type: {ct}\\r\\n\\r\\n".encode() + bytes(value[1]))
        elif isinstance(value, (bytes, bytearray)):
            out.extend(f'Content-Disposition: form-data; name="{q(name)}"; filename="{q(name)}"\\r\\n'.encode())
            out.extend(b"Content-Type: application/octet-stream\\r\\n\\r\\n" + bytes(value))
        else:
            text = str(value).lower() if isinstance(value, bool) else str(value)
            out.extend(f'Content-Disposition: form-data; name="{q(name)}"\\r\\n\\r\\n'.encode() + text.encode())
        out.extend(b"\\r\\n")

    for name, value in parts.items():
        for item in (value if isinstance(value, list) else [value]):
            part(name, item)
    out.extend(f"--{boundary}--\\r\\n".encode())
    req.raw_body = bytes(out)
    req.raw_content_type = "multipart/form-data; boundary=" + boundary


class _Calls:
    def __init__(self, http: HttpTransport) -> None:
        self._http = http

    @staticmethod
    def _apply(req: ApiRequest, o: Optional[RequestOptions]) -> ApiRequest:
        if o is None:
            return req
        if o.idempotency_key is not None:
            req.idempotency_key = o.idempotency_key
        if o.seat is not None:
            req.headers["X-Sangam-Seat"] = o.seat
        if o.acting_for_seat is not None:
            req.headers["X-Sangam-Acting-For-Seat"] = o.acting_for_seat
        if o.timeout is not None:
            req.timeout = o.timeout
        req.headers.update(o.headers)
        return req

    def json(self, req: ApiRequest, o: Optional[RequestOptions]) -> Any:
        return self._http.execute(self._apply(req, o)).body

    def none(self, req: ApiRequest, o: Optional[RequestOptions]) -> None:
        self._http.execute(self._apply(req, o))

    def raw(self, req: ApiRequest, o: Optional[RequestOptions], accept: str) -> bytes:
        req.headers["Accept"] = accept
        req.raw_response = True
        body = self._http.execute(self._apply(req, o)).body
        return body if isinstance(body, bytes) else b""

    def page(self, req: ApiRequest, o: Optional[RequestOptions], page: Optional[int], size: Optional[int]) -> Page[Any]:
        """A bare JSON array (or an object with ``items``) plus the A-16 headers X-Total-Count / -Capped."""
        r = self._http.execute(self._apply(req, o))
        body = r.body
        arr = body if isinstance(body, list) else (body.get("items") if isinstance(body, dict) else None)
        items = list(arr or [])
        total: Optional[int] = None
        h = r.header("X-Total-Count")
        if h is not None:
            try:
                total = int(h.strip())
            except ValueError:
                total = None
        capped = (r.header("X-Total-Count-Capped") or "").strip().lower() == "true"
        return Page(items, page or 0, size if size is not None else len(items), total, capped)
'''


def class_text(c: Contract, g: Group) -> str:
    out = ["", f"class {g.cls}:", f'    """``{pdoc(g.label)}`` ({len(g.ops)} operations)."""', "",
           "    def __init__(self, calls: _Calls) -> None:", "        self._c = calls"]
    for o in g.ops:
        out.append("")
        out.append(method(o))
    out.append("")
    return "\n".join(out) + "\n"


def api(c: Contract, groups: list[Group]) -> str:
    out = [header(c.version).rstrip("\n"),
           '"""Typed operations of sangam-api.yaml, one class per contract tag (large tags split by sub-path);',
           '``SangamClient.api`` returns the SangamApis facade. Bodies and results are the TypedDicts of',
           ':mod:`sangam_sdk.generated.models`."""',
           "from __future__ import annotations", SUPPORT]
    for g in groups:
        out.append(class_text(c, g).rstrip("\n"))
    out.append("")
    out.append("")
    out.append("class SangamApis:")
    out.append(f'    """The generated typed surface of sangam-api.yaml {c.version}: {len(c.operations)} operations on '
               f'{c.path_count} paths."""')
    out.append("")
    out.append("    def __init__(self, http: HttpTransport) -> None:")
    out.append("        calls = _Calls(http)")
    for g in groups:
        out.append(f"        self.{ident(g.stem)} = {g.cls}(calls)")
    return "\n".join(out) + "\n"


def emit(c: Contract, groups: list[Group]) -> dict[str, str]:
    init = (header(c.version) + '"""Generated typed surface of sangam-api.yaml (M-020). Use ``SangamClient.api``."""\n'
            "from . import models\n"
            "from .api import RequestOptions, SangamApis\n\n"
            "__all__ = [\"models\", \"RequestOptions\", \"SangamApis\"]\n")
    return {f"{BASE}/__init__.py": init, f"{BASE}/models.py": models(c), f"{BASE}/api.py": api(c, groups)}
