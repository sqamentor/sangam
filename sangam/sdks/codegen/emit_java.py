def class_text(c: Contract, g: Group) -> str:
    return api_file(c, g)


def emit(c: Contract, groups: list[Group]) -> dict[str, str]:
    for name in c.models:
        if name in USED_LANG:
            raise ValueError(f"schema {name} would shadow java.lang.{name} in the generated Java models")
    files: dict[str, str] = {}
    for m in c.models.values():
        files[f"{BASE}/model/{m.name}.java"] = model_file(c, m)
    for g in groups:
        files[f"{BASE}/api/{g.cls}.java"] = api_file(c, g)
    files[f"{BASE}/api/GeneratedCalls.java"] = header(c.version) + SUPPORT
    files[f"{BASE}/api/RequestOptions.java"] = header(c.version) + OPTIONS
    files[f"{BASE}/api/FilePart.java"] = header(c.version) + FILEPART
    files[f"{BASE}/SangamApis.java"] = facade(c, groups)
    return files
