"""TypeScript emitter: interfaces (wire names exactly) in src/generated/models.ts, one API class per tag in
src/generated/api.ts and the SangamApis facade. Runtime: the SDK's own HttpTransport (fetch); no new dependency."""
from __future__ import annotations

import re

from api_groups import Group
from contract_ir import Contract, Operation, Param, T, camel, pascal

BASE = "typescript/src/generated"
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
RESERVED = set("""break case catch class const continue debugger default delete do else enum export extends false
finally for function if import in instanceof new null return super switch this throw true try typeof var void while
with yield let static implements interface package private protected public await arguments eval""".split())


def member(name: str) -> str:
    i = camel(name)
    return i + "_" if i in RESERVED else i


def key(wire: str) -> str:
    return wire if IDENT.match(wire) else "'" + wire.replace("\\", "\\\\").replace("'", "\\'") + "'"


def tsdoc(text: str) -> str:
    return text.replace("*/", "*\\/")


def ttype(t: T, ns: str = "") -> str:
    k = t.kind
    if k == "ref":
        return ns + t.name
    if k == "string":
        return " | ".join("'" + v.replace("'", "\\'") + "'" for v in t.enum) if t.enum else "string"
    if k in ("datetime", "date", "binary"):
        return "string"
    if k in ("int32", "int64", "double", "decimal"):
        return "number"
    if k == "boolean":
        return "boolean"
    if k == "array":
        inner = ttype(t.item, ns)
        return f"Array<{inner}>"
    if k == "map":
        return f"Record<string, {ttype(t.item, ns)}>"
    return "unknown"


def header(version: str) -> str:
    return ("// SPDX-License-Identifier: Apache-2.0\n"
            f"// GENERATED by sdks/codegen/generate_sdk_surface.py from sangam-rest/api/sangam-api.yaml {version}."
            " Do not edit.\n")


def doc_block(text: str, indent: str) -> list[str]:
    lines = [l for l in tsdoc(text).splitlines()]
    if not lines:
        return []
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**"] + [f"{indent} * {l}" if l else f"{indent} *" for l in lines] + [f"{indent} */"]


def models(c: Contract) -> str:
    out = [header(c.version), "/* eslint-disable */", ""]
    for m in c.models.values():
        out += doc_block((m.description or f"Contract schema {m.name}.") + f"\n\nSchema `{m.name}`.", "")
        out.append(f"export interface {m.name} {{")
        for p in m.props:
            d = p.description + (f" One of: {', '.join(p.type.enum)}." if p.type.enum else "")
            out += doc_block(d, "  ")
            out.append(f"  {key(p.wire)}{'' if p.required else '?'}: {ttype(p.type)};")
        if m.extras is not None:
            out.append("  /** Members not named in the schema (additionalProperties). */")
            out.append("  [key: string]: unknown;")
        out.append("}")
        out.append("")
    return "\n".join(out)


def sig(op: Operation) -> tuple[list[str], list[tuple[str, Param]], str]:
    """Positional parameters, the params-object members (key, Param) and whether that object is required."""
    used = {"options", "params", "body"}
    pos = []
    names: dict[str, str] = {}
    for p in op.path_params:
        i = member(p.wire)
        while i in used:
            i += "_"
        used.add(i)
        names[p.wire] = i
        pos.append(f"{i}: {'string | number' if p.type.kind in ('int32', 'int64') else 'string'}")
    if op.body is not None:
        bt = body_type(op)
        if op.body.required:
            pos.append(f"body: {bt}")
        elif op.required_params:
            pos.append(f"body: {bt} | undefined")
        else:
            pos.append(f"body?: {bt}")
    members = [(p.wire if p.location == "query" else member(p.wire), p) for p in op.query_params + op.header_params]
    req = "required" if op.required_params else ("optional" if members else "none")
    return pos, members, req if members else "none"


def body_type(op: Operation) -> str:
    b = op.body
    if b is None:
        return ""
    if b.kind == "json":
        return ttype(b.type, "M.")
    if b.kind == "multipart":
        return "FormData"
    return "Uint8Array | string"


def result_type(op: Operation) -> str:
    r = op.response
    if r.kind == "none":
        return "void"
    if r.kind in ("raw", "sse"):
        return "Uint8Array" if not r.media.startswith("text/") and "xml" not in r.media else "string"
    if r.paged:
        return f"Page<{ttype(r.type.item, 'M.')}>"
    return ttype(r.type, "M.")


def path_expr(op: Operation, names: dict[str, str]) -> str:
    return "`" + re.sub(r"{([^}]+)}", lambda mt: "${seg(String(" + names[mt.group(1)] + "))}", op.path) + "`"


def method(op: Operation) -> str:
    pos, members, req = sig(op)
    names = {}
    for p, decl in zip(op.path_params, pos):
        names[p.wire] = decl.split(":")[0]
    args = list(pos)
    if req != "none":
        fields = []
        for k, p in members:
            d = p.description.replace("\n", " ")
            fields.append(f"{key(k)}{'' if p.required else '?'}: {ttype(p.type, 'M.')}"
                          + (f" /* {tsdoc(d)} */" if d else ""))
        args.append(f"params{'' if req == 'required' else '?'}: {{ {'; '.join(fields)} }}")
    args.append("options?: RequestOptions")
    flags = []
    if op.permission:
        flags.append(f"permission `{op.permission}`")
    if op.fenced:
        flags.append("fenced by (workerId, lockVersion, attemptId): 409 STALE_LEASE changes nothing (VI.3)")
    if op.idempotent:
        flags.append("result stored atomically with the state change")
    text = (op.summary or op.op_id)
    if op.description and op.description != op.summary:
        text += "\n\n" + op.description
    text += f"\n\n`{op.method} {op.path}` (operationId `{op.op_id}`)" + ("; " + "; ".join(flags) if flags else "") + "."
    if op.deprecated:
        text += "\n@deprecated"
    lines = doc_block(text, "  ")
    rt = result_type(op)
    lines.append(f"  async {member(op.op_id)}({', '.join(args)}): Promise<{rt}> {{")
    q = [f"{key(k)}: params?.{k if re.match(IDENT, k) else '[' + key(k) + ']'}"
         for k, p in members if p.location == "query"]
    h = [f"'{p.wire}': params?.{k if re.match(IDENT, k) else '[' + key(k) + ']'}"
         for k, p in members if p.location == "header"]
    req_parts = [f"method: '{op.method}'", f"path: {path_expr(op, names)}"]
    if q:
        req_parts.append(f"query: {{ {', '.join(q)} }}")
    lines.append(f"    const req: ApiRequest = {{ {', '.join(req_parts)} }};")
    if h:
        lines.append(f"    headersOf(req, {{ {', '.join(h)} }});")
    if op.body is not None:
        if op.body.kind == "json":
            lines.append("    if (body !== undefined) req.body = body;")
        elif op.body.kind == "multipart":
            lines.append("    if (body !== undefined) req.rawBody = body;")
        else:
            lines.append(f"    if (body !== undefined) {{ req.rawBody = body; req.rawContentType = options?.contentType ?? "
                         f"'{op.body.media}'; }}")
    r = op.response
    if r.kind == "none":
        lines.append("    await this.calls.none(req, options);")
    elif r.kind in ("raw", "sse"):
        kind = "bytes" if rt == "Uint8Array" else "text"
        lines.append(f"    return this.calls.{kind}(req, options, '{r.media}');")
    elif r.paged:
        pg = {p.wire: k for k, p in members}
        lines.append(f"    return this.calls.page<{ttype(r.type.item, 'M.')}>(req, options, params?.{pg['page']}, "
                     f"params?.{pg['size']});")
    else:
        lines.append(f"    return this.calls.json<{rt}>(req, options);")
    lines.append("  }")
    return "\n".join(lines)


SUPPORT = """import { HttpTransport, seg, type ApiRequest } from '../http.js';
import type { Page } from '../models.js';
import type * as M from './models.js';

/** Per-call options of a generated operation. */
export interface RequestOptions {
  /** `Idempotency-Key` (R41); on a mutation without one the transport generates one per logical call. */
  idempotencyKey?: string;
  /** `X-Sangam-Seat` for this call (IX.5 rule 1). */
  seat?: string;
  /** `X-Sangam-Acting-For-Seat` for this call (IX.5 rule 4). */
  actingForSeat?: string;
  timeoutMs?: number;
  /** Media type of a raw request body when the operation accepts several. */
  contentType?: string;
  headers?: Record<string, string>;
  signal?: AbortSignal;
}

function headersOf(req: ApiRequest, values: Record<string, unknown>): void {
  for (const [k, v] of Object.entries(values)) {
    if (v === undefined || v === null) continue;
    req.headers = { ...(req.headers ?? {}), [k]: String(v) };
  }
}

function apply(req: ApiRequest, o: RequestOptions | undefined): ApiRequest {
  if (!o) return req;
  if (o.idempotencyKey !== undefined) req.idempotencyKey = o.idempotencyKey;
  if (o.seat !== undefined) req.seat = o.seat;
  if (o.actingForSeat !== undefined) req.actingForSeat = o.actingForSeat;
  if (o.timeoutMs !== undefined) req.timeoutMs = o.timeoutMs;
  if (o.signal !== undefined) req.signal = o.signal;
  if (o.headers) req.headers = { ...(req.headers ?? {}), ...o.headers };
  return req;
}

/** Shared execution of the generated operations. */
export class GeneratedCalls {
  constructor(private readonly http: HttpTransport) {}

  async json<T>(req: ApiRequest, o: RequestOptions | undefined): Promise<T> {
    return this.http.call<T>(apply(req, o));
  }

  async none(req: ApiRequest, o: RequestOptions | undefined): Promise<void> {
    await this.http.execute<unknown>(apply(req, o));
  }

  async bytes(req: ApiRequest, o: RequestOptions | undefined, accept: string): Promise<Uint8Array> {
    req.headers = { ...(req.headers ?? {}), Accept: accept };
    req.responseType = 'bytes';
    return (await this.http.execute<Uint8Array>(apply(req, o))).body;
  }

  async text(req: ApiRequest, o: RequestOptions | undefined, accept: string): Promise<string> {
    req.headers = { ...(req.headers ?? {}), Accept: accept };
    req.responseType = 'text';
    return (await this.http.execute<string>(apply(req, o))).body;
  }

  /** A bare JSON array (or an object with `items`) plus the A-16 headers `X-Total-Count` / `X-Total-Count-Capped`. */
  async page<T>(req: ApiRequest, o: RequestOptions | undefined, page?: number, size?: number): Promise<Page<T>> {
    const r = await this.http.execute<unknown>(apply(req, o));
    const b = r.body as unknown;
    const arr = Array.isArray(b) ? b : (b && typeof b === 'object' && Array.isArray((b as { items?: unknown }).items)
      ? (b as { items: unknown[] }).items : []);
    const h = r.headers.get('x-total-count');
    const n = h === null ? Number.NaN : Number.parseInt(h.trim(), 10);
    return {
      items: arr as T[],
      page: page ?? 0,
      size: size ?? arr.length,
      totalCount: Number.isFinite(n) ? n : undefined,
      totalCountCapped: (r.headers.get('x-total-count-capped') ?? '').toLowerCase() === 'true',
    };
  }
}
"""


def class_text(c: Contract, g: Group) -> str:
    out = doc_block(f"Typed operations of `{g.label}` ({len(g.ops)} operations).", "")
    out.append(f"export class {g.cls} {{")
    out.append("  constructor(private readonly calls: GeneratedCalls) {}")
    out.append("")
    out.append("\n\n".join(method(o) for o in g.ops))
    out.append("}")
    return "\n".join(out) + "\n"


def api(c: Contract, groups: list[Group]) -> str:
    out = [header(c.version), SUPPORT]
    for g in groups:
        out.append(class_text(c, g))
    out += doc_block(f"The generated typed surface of sangam-api.yaml {c.version}: {len(c.operations)} operations on "
                     f"{c.path_count} paths, one member per API class (a tag, or a sub-path of a large tag). "
                     "Use `client.api`.", "")
    out.append("export class SangamApis {")
    for g in groups:
        out.append(f"  readonly {g.member}: {g.cls};")
    out.append("")
    out.append("  constructor(http: HttpTransport) {")
    out.append("    const calls = new GeneratedCalls(http);")
    for g in groups:
        out.append(f"    this.{g.member} = new {g.cls}(calls);")
    out.append("  }")
    out.append("}")
    return "\n".join(out) + "\n"


def emit(c: Contract, groups: list[Group]) -> dict[str, str]:
    index = (header(c.version) + "export type * from './models.js';\n"
             "export { SangamApis, GeneratedCalls, type RequestOptions } from './api.js';\n"
             + "".join(f"export {{ {g.cls} }} from './api.js';\n" for g in groups))
    return {f"{BASE}/models.ts": models(c), f"{BASE}/api.ts": api(c, groups), f"{BASE}/index.ts": index}
