def class_text(c: Contract, g: Group) -> str:
    out = summary(f"Typed operations of {g.label} ({len(g.ops)} operations).", "")
    out.append(f"public sealed class {g.cls}")
    out.append("{")
    out.append("    private readonly GeneratedCalls _calls;")
    out.append("")
    out.append(f"    public {g.cls}(GeneratedCalls calls) => _calls = calls;")
    out.append("")
    out.append("\n\n".join(method(o) for o in g.ops))
    out.append("}")
    return "\n".join(out) + "\n"


API_PREAMBLE = ("namespace Sangam.Sdk.Generated;\n\nusing global::Sangam.Sdk.Http;\n"
                "using M = global::Sangam.Sdk.Generated.Models;\n\n")


def support_files(c: Contract) -> dict[str, str]:
    """SUPPORT holds three types (RequestOptions, FilePart, GeneratedCalls): one file each (owner decision)."""
    body = SUPPORT[SUPPORT.index("/// <summary>Per-call options"):]
    i_file = body.index("/// <summary>One file of a multipart")
    i_calls = body.index("/// <summary>Shared execution")
    parts = {"RequestOptions": body[:i_file], "FilePart": body[i_file:i_calls], "GeneratedCalls": body[i_calls:]}
    return {f"{BASE}/{name}.g.cs": header(c.version) + API_PREAMBLE + text.rstrip("\n") + "\n"
            for name, text in parts.items()}


def facade(c: Contract, groups: list[Group]) -> str:
    out = [header(c.version) + API_PREAMBLE.rstrip("\n")]
    out += summary(f"The generated typed surface of sangam-api.yaml {c.version}: {len(c.operations)} operations on "
                   f"{c.path_count} paths, one property per API class (a tag, or a sub-path of a large tag). "
                   "Use SangamClient.Api.", "")
    out.append("public sealed class SangamApis")
    out.append("{")
    out.append("    public SangamApis(HttpTransport http)")
    out.append("    {")
    out.append("        var calls = new GeneratedCalls(http);")
    for g in groups:
        out.append(f"        {g.stem} = new {g.cls}(calls);")
    out.append("    }")
    out.append("")
    for g in groups:
        out.append(f"    public {g.cls} {g.stem} {{ get; }}")
    out.append("}")
    return "\n".join(out) + "\n"


def emit(c: Contract, groups: list[Group]) -> dict[str, str]:
    """One file per class (owner decision 2026-11-12): Models/<Schema>.g.cs, Api/<Class>.g.cs, SangamApis.g.cs and one
    file per support type. The SDK-style csproj compiles every *.cs below the project, so no glob is needed."""
    files: dict[str, str] = {}
    for m in c.models.values():
        files[f"{BASE}/Models/{m.name}.g.cs"] = (header(c.version) + "namespace Sangam.Sdk.Generated.Models;\n\n"
                                                 + "\n".join(model(m)).rstrip("\n") + "\n")
    for g in groups:
        files[f"{BASE}/Api/{g.cls}.g.cs"] = header(c.version) + API_PREAMBLE + class_text(c, g)
    files.update(support_files(c))
    files[f"{BASE}/SangamApis.g.cs"] = facade(c, groups)
    return files
