"""Generator of decision-register.json, the committed export of the E16 decision register (CR-08, CR-09, RM-39).

Reads the two inventory CSVs of the E16 review (MAVEN-INVENTORY.csv: gav, scopes, spdx, decision; NON-MAVEN-INVENTORY.csv:
ecosystem, name, version, usage_scope, spdx, decision) and writes one entry per shipped component version:
  "pkg:maven/g/a@v": {"decision": "...", "distributions": [...], "spdx": "..."}
Only rows whose use is a distribution are exported; build and test rows are covered by the build-scope review
(check_licences.py --build-scope, decision 127). The output is sorted and LF-terminated, so a regeneration that
changes nothing changes no byte. Change the CSVs (a new register row with evidence), then regenerate; never hand-edit.

  python -I sangam/deploy/licence/register_export.py --maven MAVEN-INVENTORY.csv --non-maven NON-MAVEN-INVENTORY.csv \
      --out sangam/deploy/licence/decision-register.json
"""
import argparse
import csv
import json
import re
import sys

# inventory distribution names -> distributions.json ids
MAVEN_DIST = {
    "server-fatjar": "server", "control-plane-fatjar": "control-plane", "gateway-fatjar": "gateway",
    "rollup-fatjar": "rollup", "sdk-java-jar": "sdk-java", "lib-ext separate jar": "lib-ext", "cli-shaded-jar": "cli",
    "esign-lib-dir": "esign",  # decision 217: opt-in eSign add-on (Bouncy Castle jdk18on)
    "nats-lib-dir": "nats",    # decision 232: opt-in NATS add-on (jnats and Bouncy Castle lts8on)
}


def maven_distributions(scopes):
    m = re.search(r"use=distribution \[([^\]]*)\]", scopes)
    if not m:
        return []
    out = set()
    inner = re.sub(r"\([^)]*\)", "", m.group(1))   # "(built; not a release asset)" notes hold semicolons
    for part in inner.split(";"):
        part = part.strip()
        for key, dist in MAVEN_DIST.items():
            if part.startswith(key):
                out.add(dist)
                break
        else:
            raise ValueError(f"unknown distribution {part!r} in scopes {scopes!r}")
    return sorted(out)


def maven_rows(path):
    with open(path, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            dists = maven_distributions(r["scopes"])
            if not dists:
                continue
            parts = r["gav"].split(":")
            if len(parts) not in (3, 4):
                raise ValueError(f"gav {r['gav']!r} is not group:artifact:version[:classifier]")
            g, a, v = parts[:3]   # the register is keyed without purl qualifiers (a classifier is a qualifier)
            yield f"pkg:maven/{g}/{a}@{v}", {"decision": r["decision"], "distributions": dists, "spdx": r["spdx"]}


def npm_purl(name, version):
    if name.startswith("@"):
        scope, _, rest = name[1:].partition("/")
        return f"pkg:npm/%40{scope}/{rest}@{version}"
    return f"pkg:npm/{name}@{version}"


# npm rows the ui distribution answers for: what vite bundles into dist/, and what the ui SBOM lists without being
# bundled (cyclonedx-npm --omit dev keeps devOptional packages, e.g. an optional peer of a runtime package that is
# installed as a devDependency; UP-L6: typescript, the optional peer of react-i18next 15.7 and 18). The register must cover
# every component the shipped SBOM names, so the second kind is exported for "ui" too.
NPM_UI_MARKERS = ("distribution (bundled into the UI dist", "listed in the ui SBOM")


def non_maven_rows(path):
    with open(path, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            if r["ecosystem"] == "npm" and any(m in r["usage_scope"] for m in NPM_UI_MARKERS):
                yield npm_purl(r["name"], r["version"]), {"decision": r["decision"], "distributions": ["ui"], "spdx": r["spdx"]}


def build(maven_csv, non_maven_csv):
    entries = {}
    for source in (maven_rows(maven_csv), non_maven_rows(non_maven_csv)):
        for purl, e in source:
            if purl in entries:
                prior = entries[purl]
                if prior["decision"] != e["decision"]:
                    raise ValueError(f"{purl}: two register decisions {prior['decision']!r} and {e['decision']!r}")
                prior["distributions"] = sorted(set(prior["distributions"]) | set(e["distributions"]))
            else:
                entries[purl] = e
    return {"_comment": "SPDX-License-Identifier: Apache-2.0. GENERATED by register_export.py from the E16 inventory "
                        "CSVs; do not edit. One entry per shipped component version with its decision-register label "
                        "and the distributions it is accepted for (CR-08, CR-09).",
            "components": dict(sorted(entries.items()))}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--maven", required=True)
    ap.add_argument("--non-maven", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    try:
        data = build(a.maven, a.non_maven)
    except (OSError, ValueError, KeyError) as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=1, sort_keys=False)
        f.write("\n")
    print(f"{a.out}: {len(data['components'])} shipped component versions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
