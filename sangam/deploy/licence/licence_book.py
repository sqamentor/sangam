"""THIRD-PARTY-LICENSES book of one release (M-088; ADR-D-17, LIC-11): every third-party component of every
distribution and image, with its licence terms, followed by the text of each licence once.

It is built only from the per-distribution notices bundles that notice_bundle.py wrote (release.yml: dist/notices/<id>/
THIRD-PARTY.txt and licenses/<id>.txt, the image bundles merged in), so the book cannot list a component or a licence
that the gated bundles do not. No timestamps: the same bundles give the same bytes.

Fails (exit 1, nothing written) when a distribution directory has no THIRD-PARTY.txt or a row cannot be read, when a
licence a row uses has no text in that distribution's licenses/, or when two distributions carry different texts for
the same licence id. Unreadable input is BLOCKED (exit 2). Standard library only.

  python -I licence_book.py dist/notices --version 0.1.0 --out dist/THIRD-PARTY-LICENSES-0.1.0.txt
"""
import argparse
import os
import sys

ROW_FIELDS = ("declared: ", "used: ")


class BookError(Exception):
    """The bundles are inconsistent; ``problems`` lists each one."""

    def __init__(self, problems):
        super().__init__("; ".join(problems))
        self.problems = problems


def read_text(path):
    with open(path, encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def parse_rows(dist, text):
    """Yields (purl, declared, [used ids]) from a THIRD-PARTY.txt; raises BookError on a malformed row."""
    problems = []
    for n, line in enumerate(text.split("\n"), 1):
        if "\t" not in line:
            continue  # header and blank lines
        parts = line.split("\t")
        if len(parts) != 3 or not parts[0].startswith("pkg:") or not all(
                p.startswith(f) for p, f in zip(parts[1:], ROW_FIELDS)):
            problems.append(f"{dist}/THIRD-PARTY.txt line {n} is not 'purl<TAB>declared: ...<TAB>used: ...'")
            continue
        used = parts[2][len("used: "):]
        ids = [] if used == "(none)" else [i.strip() for i in used.split(" AND ") if i.strip()]
        yield parts[0], parts[1][len("declared: "):], ids
    if problems:
        raise BookError(problems)


def collect(notices_dir):
    """Returns (components, texts): components[purl] = {"declared", "used", "distributions"}; texts[id] = text."""
    try:
        dists = sorted(d for d in os.listdir(notices_dir) if os.path.isdir(os.path.join(notices_dir, d)))
    except OSError as e:
        raise OSError(f"cannot read {notices_dir}: {e}") from e
    if not dists:
        raise BookError([f"{notices_dir} holds no distribution notices directory"])
    problems, components, texts, text_from = [], {}, {}, {}
    for dist in dists:
        base = os.path.join(notices_dir, dist)
        third = os.path.join(base, "THIRD-PARTY.txt")
        if not os.path.isfile(third):
            problems.append(f"{dist}: no THIRD-PARTY.txt")
            continue
        try:
            rows = list(parse_rows(dist, read_text(third)))
        except BookError as e:
            problems.extend(e.problems)
            continue
        for purl, declared, ids in rows:
            c = components.setdefault(purl, {"declared": set(), "used": set(), "distributions": set()})
            c["declared"].add(declared)
            c["used"].add(" AND ".join(ids) if ids else "(none)")
            c["distributions"].add(dist)
            for i in ids:
                p = os.path.join(base, "licenses", f"{i}.txt")
                if not os.path.isfile(p):
                    problems.append(f"{dist}: {purl} uses {i} but {dist}/licenses/{i}.txt is missing")
                    continue
                t = read_text(p)
                if i in texts and texts[i] != t:
                    problems.append(f"licence {i}: the text in {dist} differs from the text in {text_from[i]}")
                elif i not in texts:
                    texts[i], text_from[i] = t, dist
    if problems:
        raise BookError(sorted(set(problems)))
    return components, texts


def render(version, components, texts):
    out = [f"Sangam {version}: third-party licences\n",
           "=" * 100 + "\n",
           "Generated by sangam/deploy/licence/licence_book.py from the notices bundle of each distribution and image of\n"
           "this release (notice_bundle.py, sangam-notices-<version>.tgz). Sangam itself is licensed under the Apache\n"
           "License, Version 2.0 (LICENSE); its NOTICE and the NOTICE files of the shipped components are in the notices\n"
           "bundles. This book records licence terms; it is not legal advice.\n\n",
           f"Part 1. Components ({len(components)})\n", "-" * 100 + "\n"]
    for purl in sorted(components):
        c = components[purl]
        out.append(f"{purl}\n")
        out.append(f"    declared: {' | '.join(sorted(c['declared']))}\n")
        out.append(f"    licence used: {' | '.join(sorted(c['used']))}\n")
        out.append(f"    distributions: {', '.join(sorted(c['distributions']))}\n")
    out.append(f"\nPart 2. Licence texts ({len(texts)})\n" + "-" * 100 + "\n")
    for i in sorted(texts):
        users = sum(1 for c in components.values() if any(i in u.split(" AND ") for u in c["used"]))
        out.append(f"\n==== {i} (used by {users} component{'s' if users != 1 else ''}) ====\n\n")
        out.append(texts[i].rstrip("\n") + "\n")
    return "".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("notices", help="directory with one notices bundle per distribution (notice_bundle.py --out)")
    ap.add_argument("--version", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    try:
        components, texts = collect(a.notices)
    except BookError as e:
        for p in e.problems:
            print(f"::error title=licence book::{p}")
        print(f"licence book {a.version}: FAIL, {len(e.problems)} problem(s)")
        return 1
    except (OSError, UnicodeDecodeError) as e:
        print(f"::error title=licence book BLOCKED::{e}")
        return 2
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(a.version, components, texts))
    print(f"licence book {a.version}: PASS, {len(components)} components, {len(texts)} licence texts -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
