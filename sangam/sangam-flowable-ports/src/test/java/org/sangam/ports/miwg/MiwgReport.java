package org.sangam.ports.miwg;

import java.util.List;

/** Writes the MIWG evidence report and the expected-outcome file from the harness results (no timestamps). */
final class MiwgReport {

    private MiwgReport() {
    }

    static String expectedTsv(List<MiwgHarness.Result> results) {
        StringBuilder sb = new StringBuilder("# MIWG expected outcomes (R10-bpmn). Columns: model, import, schema, deploy, run.\n"
                + "# Any difference fails MiwgConformanceH2Test. Change a row only with a reviewed reason (regression gate).\n");
        results.forEach(r -> sb.append(r.model()).append('\t').append(r.row()).append('\n'));
        return sb.toString();
    }

    static String markdown(List<MiwgHarness.Result> results) {
        long n = results.size();
        long imp = results.stream().filter(r -> r.importResult().startsWith("PASS")).count();
        long sch = results.stream().filter(r -> r.schema().startsWith("PASS")).count();
        long dep = results.stream().filter(r -> r.deploy().startsWith("PASS")).count();
        long runApplicable = results.stream().filter(r -> !"N/A".equals(r.run())).count();
        long run = results.stream().filter(r -> "PASS".equals(r.run())).count();
        StringBuilder sb = new StringBuilder();
        sb.append("# BPMN MIWG conformance report\n\n")
                .append("Generated by `sangam-flowable-ports` MiwgConformanceH2Test (R10-bpmn); do not edit. Rewrite with ")
                .append("`-Dmiwg.write=true` after review; the test fails when this file or `miwg/expected.tsv` differs from a run.\n\n")
                .append("Models: the 22 `Reference/*.bpmn` files of the OMG BPMN MIWG test suite ")
                .append("(github.com/bpmn-miwg/bpmn-miwg-test-suite, commit ebfa3e54, CC BY 3.0).\n\n")
                .append("Stages: IMPORT = Sangam pre-deploy validator, no error; SCHEMA = Operaton BPMN model API (XSD); ")
                .append("DEPLOY = real deployment of the unchanged file (H2, ports plugin; the same files run through the full server ")
                .append("on PostgreSQL, Oracle, SQL Server and MySQL in MiwgConformanceIT); RUN = execution scenario with assertions. ")
                .append("The bpmn-js modeller round trip is `sangam-ui/src/modeller/miwgRoundTrip.test.ts`.\n\n")
                .append("## Summary\n\n| Stage | Pass | Applicable |\n|---|---|---|\n")
                .append("| IMPORT | ").append(imp).append(" | ").append(n).append(" |\n")
                .append("| SCHEMA | ").append(sch).append(" | ").append(n).append(" |\n")
                .append("| DEPLOY | ").append(dep).append(" | ").append(n).append(" |\n")
                .append("| DEPLOY refused as designed | ").append(n - dep).append(" | ").append(n).append(" |\n")
                .append("| RUN | ").append(run).append(" | ").append(runApplicable).append(" |\n\n")
                .append("## Per model\n\n| Model | Import | Schema | Deploy | Run | Scenario or reason not applicable |\n|---|---|---|---|---|---|\n");
        for (MiwgHarness.Result r : results) {
            sb.append("| ").append(r.model()).append(" | ").append(cell(r.importResult())).append(" | ").append(cell(r.schema()))
                    .append(" | ").append(cell(r.deploy())).append(" | ").append(cell(r.run())).append(" | ").append(cell(r.note()))
                    .append(" |\n");
        }
        sb.append("\nA refused deployment is the designed outcome when an executable process (isExecutable=\"true\") binds its ")
                .append("work to another vendor's engine (activiti:, kp: or zeebe: extensions, `##unspecified` or `webService` ")
                .append("implementations without an operation) or breaks a Sangam deploy rule (ADR-D-25 strict exclusive routing): ")
                .append("Sangam refuses rather than deploy a process that cannot run. Each refusal is listed with its first error ")
                .append("and is part of the regression gate.\n")
                .append("\n## Refused by security policy (SL-160)\n\n")
                .append("On the full server the SL-160 deploy allow-list checks every expression and script language in the ")
                .append("file, descriptive processes included. Two models that deploy here are refused by security policy ")
                .append("(SL-160) on the server, by owner ruling (no scanner exception):\n\n")
                .append("| Model | Server outcome | Code |\n|---|---|---|\n")
                .append("| A.2.1 | refused by security policy (SL-160) | SL160-SCRIPT (XPath conditions) |\n")
                .append("| C.8.0 | refused by security policy (SL-160) | SL160-EXPR-BEAN (`SYS.PROCESSINSTANCE_ID`) |\n\n")
                .append("MiwgConformanceIT asserts both refusals and their codes on PostgreSQL, Oracle, SQL Server and MySQL.\n");
        sb.append("\n## XPath note\n\n")
                .append("BPMN 2.0.2 section 2.2 makes XPath 1.0 the default expression language and XML Schema / WSDL the default type ")
                .append("and service languages for Process Execution Conformance. Sangam evaluates JUEL (`${...}`) and FEEL; it does not ")
                .append("evaluate XPath and ignores `definitions/@expressionLanguage`. Models whose conditions are XPath (C.1.1) are not ")
                .append("run. This gap is reported to the integrator (R10-bpmn report), not decided here.\n");
        return sb.toString();
    }

    private static String cell(String s) {
        return s.replace("|", "\\|").replace("\n", " ");
    }
}
