    /**
     * The purpose a define request describes. The attestations ({@code standardsAttested}, every data item's
     * {@code sensitive}) and {@code active} must be given: an omitted one is refused by name, never defaulted. The
     * version is the registry's (0 here; {@code LegitimateUseRegistry.define} assigns previous + 1).
     */
    static PurposeDefinition toPurpose(String code, ComplianceRequests.DefinePurposeRequest body) {
        if (body.code() != null && !body.code().equals(code)) {
            throw ApiProblem.badRequest("VALIDATION_FAILED", "body code " + body.code() + " differs from path " + code);
        }
        requireChoice(body.standardsAttested(), "standardsAttested",
                "whether the processing meets the standards the basis or exemption requires");
        requireChoice(body.active(), "active", "whether processing under the purpose may start");
        List<PurposeDefinition.DataItem> items = new java.util.ArrayList<>();
        List<ComplianceRequests.PurposeDataItem> given = body.dataItems() == null ? List.of() : body.dataItems();
        for (int i = 0; i < given.size(); i++) {
            ComplianceRequests.PurposeDataItem d = given.get(i);
            if (d == null) {
                throw ApiProblem.badRequest("VALIDATION_FAILED", "dataItems[" + i + "] is missing");
            }
            requireChoice(d.sensitive(), "dataItems[" + i + "].sensitive", "whether the item is a special category");
            items.add(new PurposeDefinition.DataItem(d.code(), d.names(), d.sensitive()));
        }
        return new PurposeDefinition(code, body.names(), body.descriptions(), items, body.basis(), body.legalRef(),
                body.subGround(), body.registerRef(), body.standardsAttested(), body.exemptions(), body.exemptionRef(),
                body.childExemptions(), body.flags(), body.retentionTrigger(), body.retention(), body.retentionClass(),
                body.recordClass(), body.recordRetention(), body.recordRetentionRef(), 0, body.active(),
                body.specialCondition());
    }

    private static void requireChoice(Boolean value, String field, String meaning) {
        if (value == null) {
            throw ApiProblem.badRequest("VALIDATION_FAILED", field + " is required (true or false): " + meaning
                    + "; it is never assumed");
        }
    }

    /**
     * Owner decision 362: the artefact a consent manager sends. {@code noticeVersion} must be given (the notice version
     * the principal consented to); an omitted one is refused by name, never read as version 0.
     */
    static ConsentManagerPort.ConsentArtefact toArtefact(String cm, ComplianceRequests.ConsentArtefactRequest b) {
        if (b.consentManagerId() != null && !b.consentManagerId().equals(cm)) {
            throw ApiProblem.badRequest("VALIDATION_FAILED", "artefact consentManagerId differs from the path");
        }
        if (b.noticeVersion() == null) {
            throw ApiProblem.badRequest("VALIDATION_FAILED", "noticeVersion is required: the version of the notice the"
                    + " data principal consented to; it is never assumed");
        }
        return new ConsentManagerPort.ConsentArtefact(b.consentManagerId(), b.artefactId(), b.principalRef(),
                b.fiduciaryId(), b.noticeKey(), b.noticeVersion(), b.languageCode(), b.purposeCodes(), b.issuedAt(),
                b.expiresAt(), b.signature());
    }

    /**
     * Owner decision 362: the transfer to evaluate. Both attestations must be given: an omitted one is refused by name,
     * never read as false.
     */
    static CrossBorderTransferGuard.TransferRequest toTransfer(ComplianceRequests.EvaluateTransferRequest b) {
        requireChoice(b.recipientSameProtectionAttested(), "recipientSameProtectionAttested",
                "whether the recipient is attested to give the same protection");
        requireChoice(b.recipientConditionMet(), "recipientConditionMet",
                "whether the recipient meets the condition the destination requires");
        return new CrossBorderTransferGuard.TransferRequest(b.destinationCountry(), b.recipient(), b.purposeCode(),
                b.dataCategories(), b.approvalRef(), b.recipientSameProtectionAttested(), b.mechanism(),
                b.impactAssessmentRef(), b.recipientConditionMet());
    }

    /** Owner decision 362: the independence of an auditor or assessor is an attestation: required, never defaulted. */
    static void requireIndependence(Boolean independent) {
        requireChoice(independent, "independent", "whether the auditor or assessor is independent");
    }

    /** Owner decision 362: the checker's attestation that the requesting officer's rank is adequate. */
    static void requireRank(ComplianceRequests.VerifyLawfulRequest b) {
        requireChoice(b.rankAdequate(), "rankAdequate", "whether the requesting officer's rank is adequate");
    }

    // ---------------------------------------------------------------- consents

    @PostMapping("/consents")
    public ResponseEntity<ConsentService.Consent> giveConsent(RequestContext ctx,
                                                              @RequestBody ComplianceRequests.GiveConsentRequest body) {
        SecurityIdentity id = identity(ctx);
        // A data principal (or their verified guardian) gives their own consent; recording consent for someone else
        // (assisted mode at a counter) needs compliance.modify.
        if (body.principalRef() != null && !body.principalRef().equals(ctx.principalId())) {
            permissions.require(ctx, Permissions.COMPLIANCE_MODIFY);
        }
        ConsentService.Consent k = api.giveConsent(id, api.toGiveConsent(id, body));
        return Lists.created("/api/v1/compliance/consents/" + k.consentId(), k.consentId(), k);
    }

    @PostMapping("/consents/{id}/withdraw")
    public ResponseEntity<ConsentService.Consent> withdrawConsent(RequestContext ctx, @PathVariable String id,
            @RequestBody(required = false) ComplianceRequests.WithdrawConsentRequest body) {
        SecurityIdentity sid = identity(ctx);
        String owner = api.consentPrincipal(sid, id);
        if (!ctx.principalId().equals(owner)) {
            permissions.require(ctx, Permissions.COMPLIANCE_MODIFY);
        }
        Set<String> purposes = body == null || body.purposes() == null ? Set.of() : body.purposes();
        return Lists.okRef(id, api.withdrawConsent(sid, id, purposes));
    }

