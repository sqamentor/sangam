    /**
     * Generates the compliance evidence report. Register P-1 (owner decision 2026-11-20, CodeQL alert 298): generation
     * inserts {@code CMP_REPORT} and writes the audit event {@code CMP_EVIDENCE_REPORT_GENERATED}, so it is a POST with
     * the period in the body (command {@code compliance.report.generate}, {@code Idempotency-Key}); this path has no
     * GET, which answers 405 and writes nothing.
     */
    @PostMapping("/reports")
    public ResponseEntity<?> report(RequestContext ctx, @RequestBody ComplianceRequests.GenerateReportRequest b) {
        SecurityIdentity id = require(ctx, Permissions.AUDIT_READ);
        if (b.from() == null) {
            throw ApiProblem.badRequest("VALIDATION_FAILED", "from is required");
        }
        if (b.to() == null) {
            throw ApiProblem.badRequest("VALIDATION_FAILED", "to is required");
        }
        var r = api.report(id, b.from(), b.to(), b.verifyChains() == null || b.verifyChains());
        if ("html".equalsIgnoreCase(b.format())) {
            return ResponseEntity.ok().contentType(MediaType.TEXT_HTML).header("X-Sangam-Report-Hash", r.hash())
                    .body(r.html());
        }
        return ResponseEntity.ok().contentType(MediaType.APPLICATION_JSON).header("X-Sangam-Report-Hash", r.hash())
                .body(r);
    }

