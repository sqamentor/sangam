package org.sangam.spike.layer;

import java.sql.SQLException;
import java.util.Map;

/**
 * SQL dialect variants used by the product layer (SANGAM.md VI.1.6, X.2.2.8).
 *
 * <p>PostgreSQL is the reference dialect. The product-layer tests run on PostgreSQL and on MySQL 8.4
 * ({@code -Dlayer.db=mysql}); the Oracle and SQL Server variants are exercised by experiments-integration. The product
 * SQL is written once and specialised only at these points:
 * <ul>
 *   <li><b>Skip-locked claim.</b> PostgreSQL {@code ... ORDER BY .. LIMIT n FOR UPDATE OF x SKIP LOCKED};
 *       MySQL 8.0+ {@code ... ORDER BY .. LIMIT n FOR UPDATE SKIP LOCKED};
 *       Oracle {@code ... AND ROWNUM <= n FOR UPDATE SKIP LOCKED} (Oracle forbids {@code FETCH FIRST}/
 *       {@code ORDER BY} together with {@code FOR UPDATE}; ROWNUM is applied before rows are skipped, so a
 *       production Oracle relay should fetch from an unbounded {@code SKIP LOCKED} cursor and stop after n rows);
 *       SQL Server {@code SELECT TOP (n) ... FROM t x WITH (UPDLOCK, READPAST, ROWLOCK)} (RCSI required).</li>
 *   <li><b>Row lock (L2 surrogate).</b> PostgreSQL/MySQL/Oracle {@code FOR UPDATE} (Oracle: {@code FOR UPDATE WAIT 2}
 *       in production); SQL Server {@code WITH (UPDLOCK, ROWLOCK)} on an index seek.</li>
 *   <li><b>Insert-if-absent.</b> PostgreSQL {@code INSERT .. ON CONFLICT DO NOTHING}; Oracle a plain insert and
 *       ORA-00001; SQL Server a plain insert and error 2627/2601; MySQL a plain insert and error 1062 (on MySQL a
 *       duplicate key rolls back only the statement, not the transaction). {@code INSERT IGNORE} is not used (it also
 *       downgrades other errors to warnings), nor {@code ON DUPLICATE KEY UPDATE k=k} (with the driver default
 *       "found rows" it reports 1 for an existing row, so "inserted" could not be told apart). MERGE is not used
 *       (it races without HOLDLOCK).</li>
 *   <li><b>Clock.</b> All lease/claim times use the database clock (A-1). MySQL: {@code UTC_TIMESTAMP(6)}.</li>
 *   <li><b>Types.</b> See {@link #types()}; booleans are stored as SMALLINT 0/1 everywhere.</li>
 * </ul>
 */
public enum Dialect {

    POSTGRESQL(Map.of(
            "{str}", "VARCHAR(255)", "{str64}", "VARCHAR(64)", "{long}", "BIGINT", "{int}", "INTEGER",
            "{small}", "SMALLINT", "{bytes32}", "BYTEA", "{blob}", "BYTEA", "{text}", "TEXT",
            "{ts}", "TIMESTAMP WITH TIME ZONE", "{identity}", "BIGINT GENERATED BY DEFAULT AS IDENTITY")),

    ORACLE(Map.of(
            "{str}", "VARCHAR2(255 CHAR)", "{str64}", "VARCHAR2(64 CHAR)", "{long}", "NUMBER(19)", "{int}", "NUMBER(10)",
            "{small}", "NUMBER(5)", "{bytes32}", "RAW(32)", "{blob}", "BLOB", "{text}", "CLOB",
            "{ts}", "TIMESTAMP WITH TIME ZONE", "{identity}", "NUMBER(19) GENERATED BY DEFAULT AS IDENTITY")),

    SQLSERVER(Map.of(
            "{str}", "NVARCHAR(255)", "{str64}", "NVARCHAR(64)", "{long}", "BIGINT", "{int}", "INT",
            "{small}", "SMALLINT", "{bytes32}", "VARBINARY(32)", "{blob}", "VARBINARY(MAX)", "{text}", "NVARCHAR(MAX)",
            "{ts}", "DATETIMEOFFSET", "{identity}", "BIGINT IDENTITY(1,1)")),

    /**
     * MySQL 8.0+ (tested on 8.4; InnoDB, utf8mb4 with the case-sensitive {@code utf8mb4_bin} collation set on every
     * table, see {@link #createTableSuffix()}). {@code {ts}} is {@code DATETIME(6)} holding UTC wall time: no 2038
     * limit (unlike {@code TIMESTAMP}) and microsecond precision (plain {@code DATETIME} is whole seconds). Every
     * clock expression is {@code UTC_TIMESTAMP(6)}, so it does not depend on the session {@code time_zone}; the JDBC
     * connection must therefore map DATETIME values as UTC (Connector/J {@code connectionTimeZone=UTC}). Index byte
     * limit (3072 bytes, 4 bytes per utf8mb4 character): the widest key, AUTH_EFFECTIVE's, is
     * (64 + 255 + 64 + 255) &times; 4 + 2 = 2554 bytes.
     */
    MYSQL(Map.of(
            "{str}", "VARCHAR(255)", "{str64}", "VARCHAR(64)", "{long}", "BIGINT", "{int}", "INT",
            "{small}", "SMALLINT", "{bytes32}", "VARBINARY(32)", "{blob}", "LONGBLOB", "{text}", "LONGTEXT",
            "{ts}", "DATETIME(6)", "{identity}", "BIGINT AUTO_INCREMENT"));

    private final Map<String, String> types;

    Dialect(Map<String, String> types) {
        this.types = types;
    }

    /** Type tokens used by {@link Schema}; e.g. {@code {ts}} → {@code TIMESTAMP WITH TIME ZONE}. */
    public Map<String, String> types() {
        return types;
    }

    /** Expands the type tokens of a portable DDL template. */
    public String expand(String template) {
        String out = template;
        for (Map.Entry<String, String> e : types.entrySet()) {
            out = out.replace(e.getKey(), e.getValue());
        }
        return out;
    }

    /** Table options appended to every {@code CREATE TABLE} (MySQL: InnoDB, utf8mb4, case-sensitive collation). */
    public String createTableSuffix() {
        return this == MYSQL ? " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin" : "";
    }

    /** Database clock expression (A-1: never the application clock). */
    public String now() {
        return switch (this) {
            case POSTGRESQL -> "CURRENT_TIMESTAMP";
            case ORACLE -> "SYSTIMESTAMP";
            case SQLSERVER -> "SYSDATETIMEOFFSET()";
            case MYSQL -> "UTC_TIMESTAMP(6)";
        };
    }

    /** {@code now() + ? milliseconds}, with one bind parameter (a long). */
    public String nowPlusMillisParam() {
        return switch (this) {
            case POSTGRESQL -> "(CURRENT_TIMESTAMP + (? * INTERVAL '1 millisecond'))";
            case ORACLE -> "(SYSTIMESTAMP + NUMTODSINTERVAL(? / 1000, 'SECOND'))";
            case SQLSERVER -> "DATEADD(millisecond, ?, SYSDATETIMEOFFSET())";
            case MYSQL -> "TIMESTAMPADD(MICROSECOND, ? * 1000, UTC_TIMESTAMP(6))";
        };
    }

    /**
     * Bitwise AND of two integer expressions: {@code BITAND} on Oracle, the {@code &} operator elsewhere (on MySQL
     * {@code BIT_AND} is an aggregate function, not the operator; {@code &} works on BIGINT).
     */
    public String bitAnd(String a, String b) {
        return this == ORACLE ? "BITAND(" + a + ", " + b + ")" : "(" + a + " & " + b + ")";
    }

    /** Suffix for a single-row FROM-less select. */
    public String fromDual() {
        return this == ORACLE ? " FROM DUAL" : "";
    }

    /**
     * A row-locking select that skips rows locked by other transactions.
     *
     * @param columns  select list, qualified with {@code alias}
     * @param table    table name
     * @param alias    table alias
     * @param where    predicate (may contain {@code ?} placeholders)
     * @param orderBy  order clause without {@code ORDER BY} (ignored on Oracle, see class comment)
     * @param limit    maximum rows (inlined as an integer literal)
     */
    public String skipLockedSelect(String columns, String table, String alias, String where, String orderBy, int limit) {
        if (limit <= 0) {
            throw new IllegalArgumentException("limit must be positive");
        }
        return switch (this) {
            case POSTGRESQL -> "SELECT " + columns + " FROM " + table + " " + alias + " WHERE " + where
                    + " ORDER BY " + orderBy + " LIMIT " + limit + " FOR UPDATE OF " + alias + " SKIP LOCKED";
            case ORACLE -> "SELECT " + columns + " FROM " + table + " " + alias + " WHERE (" + where + ") AND ROWNUM <= "
                    + limit + " FOR UPDATE SKIP LOCKED";
            case SQLSERVER -> "SELECT TOP (" + limit + ") " + columns + " FROM " + table + " " + alias
                    + " WITH (UPDLOCK, READPAST, ROWLOCK) WHERE " + where + " ORDER BY " + orderBy;
            case MYSQL -> "SELECT " + columns + " FROM " + table + " " + alias + " WHERE " + where
                    + " ORDER BY " + orderBy + " LIMIT " + limit + " FOR UPDATE SKIP LOCKED";
        };
    }

    /** A blocking row lock by key (the L2 surrogate on {@code ROOT_SEQ}). */
    public String lockingSelect(String columns, String table, String where) {
        return switch (this) {
            case POSTGRESQL, MYSQL -> "SELECT " + columns + " FROM " + table + " WHERE " + where + " FOR UPDATE";
            case ORACLE -> "SELECT " + columns + " FROM " + table + " WHERE " + where + " FOR UPDATE WAIT 2";
            case SQLSERVER -> "SELECT " + columns + " FROM " + table + " WITH (UPDLOCK, ROWLOCK) WHERE " + where;
        };
    }

    /** Whether {@code INSERT .. ON CONFLICT DO NOTHING} is available (PostgreSQL). */
    public boolean supportsOnConflictDoNothing() {
        return this == POSTGRESQL;
    }

    /** Duplicate-key classification (X.2.2.8). */
    public boolean isUniqueViolation(SQLException e) {
        for (Throwable t = e; t != null; t = t.getCause()) {
            if (t instanceof SQLException s) {
                switch (this) {
                    case POSTGRESQL -> { if ("23505".equals(s.getSQLState())) return true; }
                    case ORACLE -> { if (s.getErrorCode() == 1) return true; }
                    case SQLSERVER -> { if (s.getErrorCode() == 2627 || s.getErrorCode() == 2601) return true; }
                    // ER_DUP_ENTRY, ER_DUP_ENTRY_WITH_KEY_NAME (SQLState 23000 alone would also match FK/NOT NULL)
                    case MYSQL -> { if (s.getErrorCode() == 1062 || s.getErrorCode() == 1586) return true; }
                }
            }
        }
        return false;
    }

    /** Retryable lock/serialization failures (VI.1.6). */
    public boolean isRetryable(SQLException e) {
        String state = e.getSQLState();
        int code = e.getErrorCode();
        return switch (this) {
            case POSTGRESQL -> "40001".equals(state) || "40P01".equals(state) || "55P03".equals(state);
            case ORACLE -> code == 60 || code == 30006 || code == 8177;
            case SQLSERVER -> code == 1205 || code == 1222 || code == 3960;
            // deadlock (SQLState 40001), lock wait timeout, NOWAIT lock not granted
            case MYSQL -> code == 1213 || code == 1205 || code == 3572 || "40001".equals(state);
        };
    }
}
